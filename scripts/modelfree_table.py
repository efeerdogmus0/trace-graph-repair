"""LaTeX table of the model-free baselines of every split, from the validator reports.

usage: python scripts/modelfree_table.py --out paper/tables/modelfree.tex [--check]

For each split of the pilot, locked-test and locked-diagnostic builds the table gives, per main task,
the best constant answer (the majority-class score), for repair also the best of the three text
heuristics, and the text-only ceiling (the best any predictor can do that sees the instruction but not
the image). All values are copied from `reports/<build>/validation.json` -> `text_only_shortcuts`, which
`trace_vr.validate` computed with the real scorer from labels and instructions alone when the build was
made. The script reads no data file, no prediction and no model output; nothing here is a result of a
model. It refuses a report that is not clean, whose splits are not the tracked manifest's, or whose
sample count for a task differs from the manifest's count of main (root + edited image) samples.
`--check` compares the existing file with what would be written and exits 1 on a difference.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BUILDS = ("pilot", "pilot_test", "pilot_diag")
BOOL_TASKS = ("reachability", "critical_edge")
REPAIR = "minimal_graph_repair"
CONSTANT = {"reachability": ("always_true", "always_false"), "critical_edge": ("always_true", "always_false"),
            REPAIR: ("always_unchanged", "always_impossible")}
HEURISTICS = ("add_edge_named_by_goal_else_impossible", "add_first_listed_edge",
              "remove_edge_named_by_first_forbidden_pair")
NAMES = {"train": "pilot train", "dev": "pilot dev", "test_id": "test ID", "test_style_ood": "test style OOD",
         "test_struct_ood": "test structure OOD", "test_combined_ood": "test combined OOD",
         "test_family_ood": "diagnostic family OOD", "test_size_ood": "diagnostic size OOD"}


def rows(root: Path = ROOT):
    out = []
    for build in BUILDS:
        report = json.loads((root / "reports" / build / "validation.json").read_text())
        manifest = json.loads((root / "manifests" / ("%s.json" % build)).read_text())
        if not report["ok"] or report["error_count"] != 0:
            raise SystemExit("%s: validator report is not clean" % build)
        if report["manifest"] != "manifests/%s.json" % build:
            raise SystemExit("%s: report belongs to %s" % (build, report["manifest"]))
        probes = report["text_only_shortcuts"]
        if sorted(probes) != sorted(manifest["split_order"]):
            raise SystemExit("%s: report splits differ from the manifest" % build)
        for split in manifest["split_order"]:
            row = {"build": build, "split": split, "roots": manifest["splits"][split]["roots"]}
            for task in BOOL_TASKS + (REPAIR,):
                p = probes[split][task]
                if task != REPAIR:  # the manifest counts answers per Boolean task over the same main samples
                    balance = manifest["stats"][split]["answer_balance:%s" % task]
                    if sum(balance.values()) < p["samples"]:
                        raise SystemExit("%s/%s/%s: more probe samples than labelled samples" % (build, split, task))
                row[task] = {"samples": p["samples"], "constant": max(p[k] for k in CONSTANT[task]),
                             "text_only": p["text_only_ceiling"]}
            row[REPAIR]["heuristic"] = max(probes[split][REPAIR][k] for k in HEURISTICS)
            out.append(row)
    return out


def latex(table):
    lines = ["% Generated by scripts/modelfree_table.py from reports/*/validation.json; do not edit by hand.",
             "\\begin{tabular}{lrccccccc}", "\\toprule",
             " & & \\multicolumn{2}{c}{reachability} & \\multicolumn{2}{c}{critical edge} & "
             "\\multicolumn{3}{c}{minimal repair} \\\\",
             "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-9}",
             "split & roots & const. & text & const. & text & const. & heur. & text \\\\", "\\midrule"]
    for r in table:
        cells = [NAMES[r["split"]], str(r["roots"])]
        for task in BOOL_TASKS:
            cells += ["%.3f" % r[task]["constant"], "%.3f" % r[task]["text_only"]]
        # the heuristic score is not a round number: keep the report's four decimals
        cells += ["%.3f" % r[REPAIR]["constant"], "%.4f" % r[REPAIR]["heuristic"], "%.3f" % r[REPAIR]["text_only"]]
        lines.append(" & ".join(cells) + " \\\\")
    return "\n".join(lines + ["\\bottomrule", "\\end{tabular}"]) + "\n"


def main(argv):
    if "--out" not in argv:
        raise SystemExit(__doc__)
    out = Path(argv[argv.index("--out") + 1])
    text = latex(rows())
    if "--check" in argv:
        if not out.exists() or out.read_text() != text:
            raise SystemExit("%s is not the generator's output" % out)
        print("ok", out)
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main(sys.argv[1:])
