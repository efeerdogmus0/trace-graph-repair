"""Training exposure per arm: samples, root groups, images, and text/target token counts.

Usage: python scripts/exposure.py <manifest.json> <split> [out.md] [--tokenizer]

Settles protocol open item 3 (exposure policy and token accounting) with numbers computed
from the manifest and `arms.training_samples`, the same function `train_arm.py` uses.
Token counts use the base model's tokenizer from the local Hugging Face cache when
`--tokenizer` is given (no download: local_files_only); otherwise only characters are
counted. Image tokens are a fixed 256 per 512 px image for every arm (M3 smoke check), so
they are reported as samples x 256, not measured here.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from trace_vr import arms, dataset, tasks  # noqa: E402

IMAGE_TOKENS_PER_IMAGE = 256  # runs/a0_smoke_t4/metrics.json
BASE_MODEL = "Qwen/Qwen3.5-2B"
BASE_REVISION = "15852e8c16360a2fea060d615a32b45270f8a8fc"  # docs/protocol.md


def exposure(samples, arm, count_tokens=None):
    rows = arms.training_samples(samples, arm)
    out = {
        "samples": len(rows),
        "root_groups": len({r["graph_group_id"] for r in rows}),
        "unique_images": len({r["image_id"] for r in rows}),
        "image_ids": sorted({r["image_id"] for r in rows}),
        "by_task": {},
        "instruction_chars": 0,
        "target_chars": 0,
    }
    if count_tokens:
        out["instruction_tokens"] = 0
        out["target_tokens"] = 0
    for r in rows:
        out["by_task"][r["task"]] = out["by_task"].get(r["task"], 0) + 1
        instr = r["public_input"]["instruction"]
        target = tasks.format_target(r["training_target"])
        out["instruction_chars"] += len(instr)
        out["target_chars"] += len(target)
        if count_tokens:
            out["instruction_tokens"] += count_tokens(instr)
            out["target_tokens"] += count_tokens(target)
    out["by_task"] = dict(sorted(out["by_task"].items()))
    out["image_tokens"] = out["samples"] * IMAGE_TOKENS_PER_IMAGE
    return out


def add_overlap(table, ref="D"):
    """Images each arm shares with the reference arm (replaces the id lists by a count)."""
    ref_ids = set(table[ref]["image_ids"])
    for e in table.values():
        e["images_shared_with_" + ref] = len(ref_ids & set(e["image_ids"]))
    for e in table.values():
        del e["image_ids"]


def render(manifest_name, split, content_digest, table, tokenizer_note):
    tok = "instruction_tokens" in next(iter(table.values()))
    head = ["arm", "samples", "root groups", "unique images", "images shared with D", "image tokens",
            "instruction chars", "target chars"]
    if tok:
        head += ["instruction tokens", "target tokens", "target tokens / sample"]
    lines = [
        "# Training exposure per arm: `%s` / `%s`" % (manifest_name, split),
        "",
        "Generated by `scripts/exposure.py` from the manifest and `arms.training_samples`; do not edit by hand.",
        "",
        "Content digest: `%s`. Tokenizer: %s. Image tokens = samples x %d (fixed per image)."
        % (content_digest, tokenizer_note, IMAGE_TOKENS_PER_IMAGE),
        "Counts are per epoch; every arm is trained for the same number of epochs.",
        "",
        "| " + " | ".join(head) + " |",
        "|---|" + "---:|" * (len(head) - 1),
    ]
    for arm, e in table.items():
        row = [arm, e["samples"], e["root_groups"], e["unique_images"], e["images_shared_with_D"], e["image_tokens"],
               e["instruction_chars"], e["target_chars"]]
        if tok:
            row += [e["instruction_tokens"], e["target_tokens"],
                    "%.1f" % (e["target_tokens"] / e["samples"])]
        lines.append("| " + " | ".join(str(x) for x in row) + " |")
    lines += ["", "Samples by task:", ""]
    for arm, e in table.items():
        lines.append("- %s: %s" % (arm, ", ".join("%s %d" % kv for kv in e["by_task"].items())))
    return "\n".join(lines) + "\n"


def main(argv):
    use_tok = "--tokenizer" in argv
    args = [a for a in argv if a != "--tokenizer"]
    manifest_path, split = Path(args[0]), args[1]
    out = Path(args[2]) if len(args) > 2 else None
    dataset.check_split_allowed(split, "train")  # exposure is a training quantity
    man, _, by_split, _ = dataset.load_dataset(manifest_path)
    count = None
    note = "none (characters only)"
    if use_tok:
        from huggingface_hub import hf_hub_download
        from tokenizers import Tokenizer
        path = hf_hub_download(BASE_MODEL, "tokenizer.json", revision=BASE_REVISION, local_files_only=True)
        tk = Tokenizer.from_file(path)
        count = lambda s: len(tk.encode(s, add_special_tokens=False).ids)  # noqa: E731
        note = "`%s@%s` tokenizer.json (local cache), text only, no chat template" % (BASE_MODEL, BASE_REVISION[:8])
    table = {arm: exposure(by_split[split], arm, count) for arm in arms.ARMS}
    add_overlap(table)
    md = render(man["name"], split, man["content_digest"], table, note)
    if out:
        out.write_text(md, encoding="utf-8")
    print(md)
    print("EXPOSURE-JSON " + json.dumps(table, sort_keys=True))


if __name__ == "__main__":
    main(sys.argv[1:])
