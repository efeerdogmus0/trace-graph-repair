"""How many distinct topologies each family generator yields per node count (protocol item 7).

Draws K graphs per (family, n) from the real generator with independent seeds and counts
isomorphism classes. Reports, per cell, the distinct classes seen, singletons/doubletons, a
Chao1 lower-bound estimate of the reachable class count, and the marginal duplicate rate at
a target number of distinct roots: of the draws made while the distinct count went from
0.9*target to target, the fraction that were duplicates. "inf" means the target was never
reached in K draws. No model, no data build; deterministic given the arguments.

usage: python scripts/topology_capacity.py [K] [target] [families,comma,sep] [nmin] [nmax] [out.md]
"""
from __future__ import annotations

import json
import sys
import time
from typing import Dict, List

from trace_vr import families
from trace_vr.iso import TopologyRegistry
from trace_vr.rng import Rng


def scan_cell(family: str, n: int, k: int, target: int) -> Dict[str, object]:
    reg = TopologyRegistry()
    counts: Dict[str, int] = {}
    distinct_after: List[int] = []
    for i in range(k):
        g = families.generate(family, n, Rng("topology-capacity", family, n, i))
        hit = reg.find_other_group(g, "draw%d" % i)
        if hit is None:
            reg.add(g, "draw%d" % i)
            counts["draw%d" % i] = 1
        else:
            counts[hit] += 1
        distinct_after.append(len(counts))
    d = len(counts)
    f1 = sum(1 for c in counts.values() if c == 1)
    f2 = sum(1 for c in counts.values() if c == 2)
    chao1 = d + (f1 * f1 / (2.0 * f2) if f2 else f1 * (f1 - 1) / 2.0)
    lo = int(round(0.9 * target))
    if d >= target:
        start = next(i for i, x in enumerate(distinct_after) if x >= lo)
        end = next(i for i, x in enumerate(distinct_after) if x >= target)
        draws = end - start + 1
        new = distinct_after[end] - (distinct_after[start - 1] if start else 0)
        marginal = 1.0 - new / float(draws)
    else:
        marginal = None
    return {"family": family, "n": n, "draws": k, "distinct": d, "singletons": f1,
            "doubletons": f2, "chao1": round(chao1, 1), "target": target,
            "dup_rate_at_target": marginal}


def main(argv: List[str]) -> None:
    k = int(argv[1]) if len(argv) > 1 else 3000
    target = int(argv[2]) if len(argv) > 2 else 430
    fams = argv[3].split(",") if len(argv) > 3 else ["layered_dag", "tree_plus", "sparse_random"]
    nmin = int(argv[4]) if len(argv) > 4 else 5
    nmax = int(argv[5]) if len(argv) > 5 else 10
    out = argv[6] if len(argv) > 6 else None
    rows = []
    t0 = time.time()
    for fam in fams:
        for n in range(max(nmin, families.MIN_NODES[fam]), nmax + 1):
            r = scan_cell(fam, n, k, target)
            rows.append(r)
            print(json.dumps(r), flush=True)
    secs = time.time() - t0
    if out:
        lines = [
            "# Topology capacity per family and node count",
            "",
            "Generated by `scripts/topology_capacity.py %d %d %s %d %d` (%.0f s). Each cell: %d draws"
            % (k, target, ",".join(fams), nmin, nmax, secs, k),
            "from the generator with independent seeds, counted up to directed-graph isomorphism.",
            "Chao1 is a lower-bound estimate of reachable classes (draws are not uniform over classes).",
            "`dup@target`: fraction of draws that were duplicates while the distinct count rose from",
            "90%% to 100%% of the target (%d distinct roots per cell); `inf` = target not reached (JSON: null)." % target,
            "",
            "| family | n | distinct | singletons | doubletons | Chao1 | dup@target |",
            "|---|---:|---:|---:|---:|---:|---:|",
        ]
        for r in rows:
            dr = r["dup_rate_at_target"]
            lines.append("| %s | %d | %d | %d | %d | %.1f | %s |" % (
                r["family"], r["n"], r["distinct"], r["singletons"], r["doubletons"], r["chao1"],
                "inf" if dr is None else "%.3f" % dr))
        with open(out, "w") as fh:
            fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv)
