"""Does a larger `find_layout` budget raise acceptance of large graphs and remove the edge bias?

Runs `layout_capacity.scan_cell` on the same seeds at several budgets. Proposal seeds are
indexed, so a larger budget tries a superset of the proposals of a smaller one.

Usage: python scripts/layout_budget.py draws families nmin nmax styles budgets out.md
       e.g. 40 sparse_random,layered_dag,two_cluster 15 18 a,b,c 180,720 docs/layout_budget.md
"""
from __future__ import annotations

import importlib.util
import json
import os
import sys
import time
from typing import Dict, List

from trace_vr import families

_spec = importlib.util.spec_from_file_location(
    "layout_capacity", os.path.join(os.path.dirname(os.path.abspath(__file__)), "layout_capacity.py"))
lc = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lc)


def pooled(rows: List[Dict]) -> Dict:
    draws = sum(r["draws"] for r in rows)
    acc = sum(r["accepted"] for r in rows)
    rej = draws - acc
    ea = sum((r["mean_edges_accepted"] or 0) * r["accepted"] for r in rows)
    er = sum((r["mean_edges_rejected"] or 0) * (r["draws"] - r["accepted"]) for r in rows)
    return {"draws": draws, "accepted": acc, "accept_rate": round(acc / float(draws), 3),
            "mean_edges_accepted": round(ea / acc, 2) if acc else None,
            "mean_edges_rejected": round(er / rej, 2) if rej else None,
            "pixel_problems": sum(r["pixel_problems"] for r in rows),
            "s_per_graph": round(sum(r["s_per_graph"] * r["draws"] for r in rows) / draws, 3)}


def main(argv: List[str]) -> None:
    k = int(argv[1])
    fams = argv[2].split(",")
    nmin, nmax = int(argv[3]), int(argv[4])
    styles = argv[5].split(",")
    budgets = [int(b) for b in argv[6].split(",")]
    out = argv[7]
    t0 = time.time()
    table = []
    for fam in fams:
        for n in range(max(nmin, families.MIN_NODES[fam]), nmax + 1):
            for b in budgets:
                rows = [lc.scan_cell(fam, n, sid, k, budget=b) for sid in styles]
                p = pooled(rows)
                p.update({"family": fam, "n": n, "budget": b})
                table.append(p)
                print(json.dumps(p), flush=True)
    secs = time.time() - t0
    lines = [
        "# Layout acceptance vs `find_layout` budget (%d px)" % lc.SIZE, "",
        "Generated by `scripts/layout_budget.py %d %s %d %d %s %s` (%.0f s). Per row: %d graphs per"
        % (k, ",".join(fams), nmin, nmax, ",".join(styles), ",".join(map(str, budgets)), secs, k),
        "style, styles pooled; same graph seeds at every budget. `edges acc / rej` is the mean edge",
        "count of accepted / rejected graphs (the selection bias layout rejection puts on a split).", "",
        "| family | n | budget | accept | edges acc / rej | pixel problems | s/graph |",
        "|---|---|---|---|---|---|---|",
    ]
    for p in table:
        lines.append("| %s | %d | %d | %d/%d (%.2f) | %s / %s | %d | %.2f |" % (
            p["family"], p["n"], p["budget"], p["accepted"], p["draws"], p["accept_rate"],
            p["mean_edges_accepted"], p["mean_edges_rejected"], p["pixel_problems"], p["s_per_graph"]))
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv)
