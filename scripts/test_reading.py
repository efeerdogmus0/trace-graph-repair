"""Locked-test reading paragraph, generated from the primary statistic (CPU only).

Usage: python scripts/test_reading.py [--primary reports/final/final_primary.json]
                                      [--out reports/final/test_reading.tex]

paper/sections/test_results.tex \\inputs the output through \\IfFileExists right after the primary table, so the
section states in words what the table holds without any number typed by hand.

Rule `reading-v1`, written 2026-11-22 AFTER the locked test was opened (08:50Z). Because the result was known when
this was written, the template is descriptive only and outcome-blind: every difference row of final_primary.json is
rendered, in file order, with the same sentence frame (six-cell point and interval, per-task points and intervals,
seed-matched range, split-sign flag, the reading label the pre-registered script recorded). No adjective, row choice
or ordering depends on a value; the reading labels are quoted, never re-derived. Refuses while the file is missing."""
import importlib.util, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULE = "reading-v1"
_spec = importlib.util.spec_from_file_location("result_summary", ROOT / "scripts/result_summary.py")
rs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rs)
PRIMARY = rs.PRIMARY
TASK_NAME = {"reachability": "reachability", "critical_edge": "critical edge"}


def _ci(e):
    return "$%+.3f$ [$%+.3f$, $%+.3f$]" % (e["point"], e["lo"], e["hi"])


def sentence(d, tasks):
    diff = d["diff"]
    seeds = d.get("seed_matched") or {}
    parts = ["\\textbf{%s$-$%s:} six-cell mean %s" % (d["a"], d["b"], _ci(diff[PRIMARY]))]
    per_task = ["%s %s" % (TASK_NAME.get(k, k.replace("_", " ")), _ci(diff[k])) for k in tasks if k in diff]
    if per_task:
        parts.append("; " + ", ".join(per_task))
    if seeds:
        v = sorted(seeds.values())
        parts.append("; seed-matched differences from $%+.3f$ to $%+.3f$ (%d seed%s)"
                     % (v[0], v[-1], len(v), "" if len(v) == 1 else "s"))
    if "splits_same_sign" in d:
        parts.append("; same sign on every split: %s" % ("yes" if d["splits_same_sign"] else "no"))
    parts.append("; recorded reading \\texttt{%s}." % d["reading"].replace("_", "\\_"))
    return "".join(parts)


def render(t):
    rs.parts(t)  # same refusal rules as the other generated texts
    tasks = list(t.get("tasks") or [])
    lines = ["%% generated by scripts/test_reading.py, rule %s, from reports/final/final_primary.json; do not edit" % RULE,
             "\\paragraph{Reading of the primary table.} Each difference below is pooled over seeds with its 95\\%% "
             "root-graph interval, as in Table~\\ref{tab:test-primary}; the reading is the label the pre-registered "
             "rule assigned, copied from the script output. Only the D$-$%s row decides the hypothesis." % t["reference"],
             "\\begin{itemize}"]
    lines += ["\\item " + sentence(d, tasks) for d in t["differences"]]
    lines.append("\\end{itemize}")
    return "\n".join(lines) + "\n"


def main(argv):
    opts = {"primary": str(ROOT / "reports/final/final_primary.json"), "out": str(ROOT / "reports/final/test_reading.tex")}
    args = list(argv)
    for key in list(opts):
        if "--" + key in args:
            i = args.index("--" + key); opts[key] = args[i + 1]; del args[i:i + 2]
    if args:
        raise SystemExit(__doc__)
    text = render(rs.load(opts["primary"]))
    out = Path(opts["out"]); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print("wrote %s" % out)


if __name__ == "__main__":
    main(sys.argv[1:])
