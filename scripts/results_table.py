"""Per-arm dev results table generated only from saved flag files (CPU only).

Usage:
  python scripts/results_table.py <manifest> --ref LABEL LABEL=flags.json [LABEL=flags.json ...]
         [--out-json f.json] [--out-md f.md] [--out-tex f.tex] [--boot 2000]

Every flag file must cover the same split, root graphs, sample set and dataset build. For each arm the
table gives per-task accuracy and the non-edit macro with root-graph bootstrap intervals, and the paired
difference to the reference arm (same resampled roots). The LaTeX output is meant to be \\input into the
paper, so no number in the results table is typed by hand."""
import json, sys
from pathlib import Path
from trace_vr import arms, bootstrap, dataset

MACRO = "non_edit_macro_accuracy"


def parse(argv):
    args = list(argv)
    opts = {"boot": 2000, "ref": None, "out-json": None, "out-md": None, "out-tex": None}
    for key in list(opts):
        flag = "--" + key
        if flag in args:
            i = args.index(flag); opts[key] = args[i + 1]; del args[i:i + 2]
    if not args or opts["ref"] is None:
        raise SystemExit(__doc__)
    manifest, pairs = args[0], []
    for a in args[1:]:
        if "=" not in a:
            raise SystemExit("expected LABEL=path, got %r" % a)
        label, path = a.split("=", 1)
        pairs.append((label, Path(path)))
    labels = [l for l, _ in pairs]
    if len(set(labels)) != len(labels):
        raise SystemExit("duplicate arm label")
    if opts["ref"] not in labels:
        raise SystemExit("--ref %s is not one of the arms" % opts["ref"])
    return manifest, pairs, opts


def build(manifest, pairs, ref, n_boot):
    man, _, by_split, _ = dataset.load_dataset(Path(manifest))
    payloads = {}
    key = None
    for label, path in pairs:
        p = json.loads(path.read_text())
        if p["content_digest"] != man["content_digest"]:
            raise SystemExit("%s comes from a different dataset build" % path)
        k = (p["split"], p["eval_root_graphs"], p.get("sample_set", "main"))
        if key is None:
            key = k
        elif k != key:
            raise SystemExit("%s covers different samples %s than %s" % (path, k, key))
        if p.get("missing_responses"):
            raise SystemExit("%s has %d missing responses" % (path, p["missing_responses"]))
        payloads[label] = (path, p)
    rows = arms.eval_samples(by_split[key[0]], key[1])
    flags = {l: bootstrap.decode_flags(rows, p) for l, (_, p) in payloads.items()}
    table = {"split": key[0], "root_graphs": key[1], "sample_set": key[2], "reference": ref,
             "content_digest": man["content_digest"], "n_boot": n_boot, "arms": []}
    for label, _ in pairs:
        path, p = payloads[label]
        res = bootstrap.cluster_bootstrap(rows, flags[label], None if label == ref else flags[ref], n_boot=n_boot)
        table["arms"].append({
            "label": label, "file": str(path), "run": p.get("run"), "input_mode": p.get("input_mode"),
            "predictions_sha256": p.get("predictions_sha256"), "images_digest": p.get("images_digest"),
            "acc": res["a"], "vs_ref": res.get("a_minus_b")})
    table["tasks"] = [k for k in table["arms"][0]["acc"] if k != MACRO] + [MACRO]
    return table


SHORT = {"minimal_graph_repair": "Repair", "reachability": "Reach.", "critical_edge": "Crit. edge", MACRO: "Non-edit macro"}


def markdown(t):
    tasks = t["tasks"]
    head = "| Arm | " + " | ".join(SHORT.get(k, k) for k in tasks) + " | macro - %s |" % t["reference"]
    lines = ["Dev split `%s`, %d root graphs, %s samples, %d bootstrap replicates over root graphs (95%%)."
             % (t["split"], t["root_graphs"], t["sample_set"], t["n_boot"]), "", head,
             "|" + "---|" * (len(tasks) + 2)]
    for a in t["arms"]:
        cells = []
        for k in tasks:
            e = a["acc"].get(k)
            cells.append("-" if e is None else "%.3f [%.3f, %.3f]" % (e["point"], e["lo"], e["hi"]))
        d = (a["vs_ref"] or {}).get(MACRO)
        cells.append("ref" if a["label"] == t["reference"] else "%+.3f [%+.3f, %+.3f]" % (d["point"], d["lo"], d["hi"]))
        lines.append("| %s | %s |" % (a["label"], " | ".join(cells)))
    return "\n".join(lines) + "\n"


def latex(t):
    tasks = t["tasks"]
    cols = "l" + "c" * (len(tasks) + 1)
    out = ["% Generated by scripts/results_table.py; do not edit by hand.",
           "\\begin{tabular}{%s}" % cols, "\\toprule",
           "Arm & " + " & ".join(SHORT.get(k, k) for k in tasks) + " & $\\Delta$ macro vs %s \\\\" % t["reference"].replace("_", "\\_"),
           "\\midrule"]
    for a in t["arms"]:
        cells = []
        for k in tasks:
            e = a["acc"].get(k)
            cells.append("--" if e is None else "%.3f" % e["point"])
        d = (a["vs_ref"] or {}).get(MACRO)
        cells.append("ref" if a["label"] == t["reference"]
                     else "$%+.3f$ {\\scriptsize[$%+.3f$, $%+.3f$]}" % (d["point"], d["lo"], d["hi"]))
        out.append("%s & %s \\\\" % (a["label"].replace("_", "\\_"), " & ".join(cells)))
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"


def main(argv):
    manifest, pairs, opts = parse(argv)
    t = build(manifest, pairs, opts["ref"], int(opts["boot"]))
    md = markdown(t)
    for key, text in (("out-json", json.dumps(t, indent=1) + "\n"), ("out-md", md), ("out-tex", latex(t))):
        if opts[key]:
            Path(opts[key]).parent.mkdir(parents=True, exist_ok=True)
            Path(opts[key]).write_text(text)
    print(md, end="")


if __name__ == "__main__":
    main(sys.argv[1:])
