"""Paper conclusion section body, generated from the primary statistic (CPU only).

Usage: python scripts/paper_conclusion.py [--primary reports/final/final_primary.json]
                                          [--out reports/final/conclusion.tex]

paper/sections/conclusion.tex \\inputs the output through \\IfFileExists; until this script has run the section says
that no result is claimed.

Rule `conclusion-v1`, fixed 2026-11-20 before any locked-test number was read (PLAN items 37 and 44 left the
conclusion open "after the primary reading"; writing it after the reading would let the result choose the words):
- the only input is final_primary.json; the reading of D against the recorded reference, its refusals and the numbers
  sentence are imported from scripts/paper_finding.py (which imports result_summary.py), so abstract, intro and
  conclusion cannot disagree.
- three paragraphs: what the paper contributes whatever the result (fixed), what the pre-registered comparison says
  (finding sentence + numbers + one fixed interpretation per reading), and what this does not show plus what would
  test it further (pilot-scale sentence + one fixed next-step sentence per reading).
- no secondary number (task_drop, splits, E - D, C - reference) appears; the text points to the test-results section.
- refuses and writes nothing while the primary file is missing; do not edit the sentences after the reading."""
import importlib.util, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULE = "conclusion-v1"
_spec = importlib.util.spec_from_file_location("paper_finding", ROOT / "scripts/paper_finding.py")
pf = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(pf)
rs = pf.rs
READINGS = pf.READINGS

CONTRIB = ("We built a procedural benchmark of drawn directed graphs in which every label and every optimal repair is "
           "checked by an independent verifier, answer-flipping twins bound any image-blind predictor at $0.50$ per task, "
           "and splits are grouped by root graph with held-out styles, families and sizes. On it we ran a pre-registered, "
           "exposure-matched comparison of repair training against question-answering and structural fine-tuning, with "
           "oracle-graph and parse-and-solve conditions that separate perception errors from reasoning errors. We "
           "release the generator, verifier, protocol, frozen evaluation code and per-sample results so the comparison "
           "can be rerun or extended.")
MEANING = {
    "positive_clear": "Within this setting, learning to make a minimal verified edit carried over to questions the model "
                      "was never trained to answer, by more than the margin we fixed in advance.",
    "positive": "Within this setting the direction favours repair training, but the margin is smaller than the one we "
                "fixed in advance, so we read it as weak support rather than a demonstrated transfer.",
    "negative": "Within this setting, learning to make a minimal verified edit did not carry over to non-edit questions as "
                "well as training on those questions directly; Section~\\ref{sec:negative} records the development "
                "observations that pointed the same way.",
    "inconclusive": "Within this setting the experiment does not tell repair training apart from the reference arm, so "
                    "it neither supports nor rules out transfer from editing to reading.",
    "incomplete_seeds": "Because the pre-registered rule needs every seed, this comparison remains open.",
}
NEXT = {
    "positive_clear": "Whether the effect survives more training data, a second base model, and real rather than "
                      "synthetic diagrams is the next question; the released protocol can be rerun unchanged for each.",
    "positive": "A larger run with more seeds, a second base model and real diagrams would show whether the small "
                "advantage is real; the released protocol can be rerun unchanged for each.",
    "negative": "A negative result at pilot scale does not rule out transfer with more data, a larger model or a "
                "different edit budget; the released protocol can be rerun unchanged to test each of these.",
    "inconclusive": "More seeds, more training data or a second base model are needed to decide; the released protocol "
                    "can be rerun unchanged for each.",
    "incomplete_seeds": "Running the missing seed under the same frozen code is the only step needed before this section "
                        "can state a result.",
}
LIMITS = "Section~\\ref{sec:limitations} lists the controls we did not run and the other limits of this study."


def render(t):
    ref, d, _diffs, _arms = rs.parts(t)
    r = d["reading"]
    tag = "%% generated by scripts/paper_conclusion.py, rule %s, from reports/final/final_primary.json; do not edit\n" % RULE
    paras = [CONTRIB,
             " ".join([pf.FINDING[r], pf.numbers(ref, d), MEANING[r],
                       "Per-split, per-task and secondary comparisons are in Section~\\ref{sec:test-results}."]),
             " ".join([pf.SCALE, NEXT[r], LIMITS])]
    return tag + "\n\n".join(paras) + "\n"


def main(argv):
    opts = {"primary": str(ROOT / "reports/final/final_primary.json"), "out": str(ROOT / "reports/final/conclusion.tex")}
    args = list(argv)
    for key in list(opts):
        if "--" + key in args:
            i = args.index("--" + key); opts[key] = args[i + 1]; del args[i:i + 2]
    if args:
        raise SystemExit(__doc__)
    text = render(rs.load(opts["primary"]))
    out = Path(opts["out"]); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print("wrote %s" % out)


if __name__ == "__main__":
    main(sys.argv[1:])
