"""LaTeX table of a seed-pooled VGCure comparison, from the JSON files scripts/vgcure_seed_pool.py wrote.

usage: python scripts/vgcure_table.py <vs_B.json> <vs_C.json> --out <tex> [--check]

Each input holds the same runs pooled against a different reference arm (the first arm given to
vgcure_seed_pool.py). The script refuses if the two files disagree on the subset, the bootstrap settings or
any arm's runs or pooled scores, so one table never mixes two evaluations. It reads no predictions.
`--check` compares the existing file with what would be written and exits 1 on a difference.
"""
import json, sys
from pathlib import Path

KEYS = ("edge_exists_accuracy", "reachability_balanced_accuracy", "external_macro")
SAME = ("subset_sha256", "record", "graphs", "n", "resamples", "seed")
NAMES = {"A": "A frozen base", "B": "B QA-SFT", "C": "C structural", "D": "D repair", "E": "E parse-and-solve"}


def load(paths):
    tabs = [json.loads(Path(p).read_text()) for p in paths]
    first = tabs[0]
    arms = {}
    for t in tabs:
        for k in SAME:
            if t[k] != first[k]:
                raise SystemExit("inputs disagree on %s" % k)
        for a, r in t["arms"].items():
            seen = arms.setdefault(a, {"runs": r["runs"], "pooled": r["pooled"], "diff": {}})
            if seen["runs"] != r["runs"] or any(abs(seen["pooled"][k] - r["pooled"][k]) > 1e-12 for k in KEYS):
                raise SystemExit("inputs disagree on arm %s" % a)
            if "diff_pooled" in r:
                seen["diff"][t["reference"]] = r["diff_pooled"]["external_macro"]
    refs = [t["reference"] for t in tabs]
    if len(set(refs)) != len(refs):
        raise SystemExit("two inputs share a reference arm")
    if len({len(r["runs"]) for r in arms.values()}) != 1:
        raise SystemExit("arms have different numbers of seeds")
    return {**{k: first[k] for k in SAME}, "references": refs, "arms": arms}


def signed(x):
    return "$%s%.3f$" % ("+" if x >= 0 else "-", abs(x))


def latex(t):
    refs = t["references"]
    lines = ["% Generated by scripts/vgcure_table.py; do not edit by hand.",
             "%% subset %s (%s), %d graphs, %d items" % (t["subset_sha256"][:12], t["record"], t["graphs"], t["n"]),
             "\\begin{tabular}{lcccc%s}" % ("c" * len(refs)), "\\toprule",
             "Arm & Seeds & Edge acc. & Reach.\\ bal.\\ acc. & Macro%s \\\\" % "".join(
                 " & $\\Delta$ macro vs %s" % r for r in refs), "\\midrule"]
    for a in sorted(t["arms"]):
        r = t["arms"][a]
        cells = [NAMES.get(a, a), str(len(r["runs"]))] + ["%.3f" % r["pooled"][k] for k in KEYS]
        for ref in refs:
            d = r["diff"].get(ref)
            cells.append("ref" if a == ref else "--" if d is None else
                         "%s {\\scriptsize[%s, %s]}" % (signed(d["point"]), signed(d["lo"]), signed(d["hi"])))
        lines.append(" & ".join(cells) + " \\\\")
    return "\n".join(lines + ["\\bottomrule", "\\end{tabular}"]) + "\n"


def main(argv):
    if "--out" not in argv:
        raise SystemExit(__doc__)
    out = Path(argv[argv.index("--out") + 1])
    paths = [a for i, a in enumerate(argv) if not a.startswith("--") and (i == 0 or argv[i - 1] != "--out")]
    text = latex(load(paths))
    if "--check" in argv:
        if not out.exists() or out.read_text() != text:
            raise SystemExit("%s is not the generator's output" % out)
        print("ok", out)
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text, end="")


if __name__ == "__main__":
    main(sys.argv[1:])
