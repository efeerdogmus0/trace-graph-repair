"""LaTeX compute table and the numbers quoted in the reproducibility appendix, from the budget report.

usage: python scripts/compute_table.py [--out paper/tables/compute.tex] [--check]

Reads `reports/budget.json` (written by `scripts/budget_report.py` from `runs/budget.jsonl`) and refuses
it unless it equals a fresh summary of the log, so the paper can never quote a stale report. The output
defines one macro per number used in prose (`\\computeMeasuredHours` ...) and the table body; the
section text holds no digits of its own. Nothing here is a model result: GPU seconds are a cost.
Rerun after every new budget line (after `scripts/budget_report.py`); `--check` exits 1 on a difference.
"""
import importlib.util, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULE = "compute-table-v1"
# short row names for the paper; a group key missing here stops the script
SHORT = {
    "smoke": "Smoke and overfit checks",
    "pilot1": "One-epoch pilot (arms A, B, D)",
    "pilot3": "Three-epoch dev pilot (all arms, seeds, oracle)",
    "base_prompt": "Frozen-base prompt scan (dev)",
    "vgcure": "External evaluation (VGCure)",
    "final": "Locked-test evaluation kernels",
    "repro": "Clean-clone GPU rerun (dev, arm D)",
}
ORDER = ("smoke", "pilot1", "pilot3", "base_prompt", "vgcure", "final", "repro")
PLATFORM = {"colab": "Google Colab", "kaggle": "Kaggle"}


def _budget_module():
    spec = importlib.util.spec_from_file_location("budget_report", ROOT / "scripts/budget_report.py")
    mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod


def load(root: Path = ROOT):
    report = json.loads((root / "reports" / "budget.json").read_text())
    mod = _budget_module()
    rows, _notes = mod.load(root / "runs" / "budget.jsonl")
    if mod.summarise(rows) != report:
        raise SystemExit("reports/budget.json is stale; run scripts/budget_report.py first")
    if report["rule"] != "budget-report-v1":
        raise SystemExit("unknown budget report rule %r" % report["rule"])
    unknown = [g["key"] for g in report["groups"] if g["key"] not in SHORT]
    if unknown:
        raise SystemExit("no paper name for group(s) %s; add them to SHORT" % unknown)
    return report


def hours(seconds: float) -> str:
    return "%.2f" % (seconds / 3600.0)


def latex(report) -> str:
    groups = {g["key"]: g for g in report["groups"]}
    total = report["measured"]
    devices = {}
    for p in report["platforms"].values():
        for device, n in p["device_recorded"].items():
            devices[device] = devices.get(device, 0) + n
    recorded = sorted(d for d in devices if d != "not recorded")
    if recorded != ["Tesla T4"]:
        raise SystemExit("devices %s: the prose assumes one recorded device, the T4; rewrite it" % recorded)
    if any(u["platform"] != "colab" for u in report["unmeasured_lines"]):
        raise SystemExit("an untimed run is not on Colab: the prose says Colab runs; rewrite it")
    macros = {
        "computeCash": str(report["cash_cost"]),
        "computeMeasuredHours": hours(total["gpu_seconds"]),
        "computeMeasuredRuns": str(total["lines"]),
        "computeLogLines": str(report["lines"]),
        "computeUnmeasuredRuns": str(len(report["unmeasured_lines"])),
        "computeFailedRuns": str(report["measured_failed"]["lines"]),
        "computeFailedMinutes": "%.1f" % (report["measured_failed"]["gpu_seconds"] / 60.0),
        "computeDeviceUnrecorded": str(devices.get("not recorded", 0)),
        "computeFinalHours": hours(groups["final"]["gpu_seconds"]) if "final" in groups else "0.00",
        "computeFinalKernels": str(groups["final"]["lines"]) if "final" in groups else "0",
    }
    lines = ["%% Generated by scripts/compute_table.py (rule %s) from reports/budget.json; do not edit by hand." % RULE]
    lines += ["\\newcommand{\\%s}{%s}" % (k, v) for k, v in macros.items()]
    lines += ["\\newcommand{\\computeTable}{%", "\\begin{tabular}{@{}lrrr@{}}", "\\toprule",
              "Purpose & lines timed & GPU hours & lines not timed \\\\", "\\midrule"]
    for key in ORDER:
        if key in groups:
            g = groups[key]
            lines.append("%s & %d & %s & %d \\\\" % (SHORT[key], g["lines"], hours(g["gpu_seconds"]),
                                                     g["lines_without_seconds"]))
    lines += ["\\midrule"]
    for name, p in report["platforms"].items():
        lines.append("%s & %d & %s & %d \\\\" % (PLATFORM.get(name, name), p["lines"], hours(p["gpu_seconds"]),
                                                 p["lines_total"] - p["lines"]))
    lines += ["\\midrule",
              "Total & %d & %s & %d \\\\" % (total["lines"], hours(total["gpu_seconds"]), report["lines"] - total["lines"]),
              "\\bottomrule", "\\end{tabular}}"]
    return "\n".join(lines) + "\n"


def main(argv):
    out = ROOT / "paper" / "tables" / "compute.tex"
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1])
    text = latex(load())
    if "--check" in argv:
        if not out.exists() or out.read_text() != text:
            print("stale: %s" % out)
            return 1
        print("ok", out)
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(text, end="")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
