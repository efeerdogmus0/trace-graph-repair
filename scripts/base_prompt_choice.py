"""Pick the frozen base's prompt variant from finished dev runs (rule: trace_vr/base_prompt.py).

Usage: python scripts/base_prompt_choice.py <runs_dir> [--out choice.json] [--out-md choice.md]

Reads <runs_dir>/base_prompt_<variant>/token_budget_dev.json for every variant (written by
scripts/token_budget.py inside scripts/colab/base_prompt.sh). Needs all variants; chooses nothing
otherwise. Prints one BASE-PROMPT line. No model, no network.
"""
import json, sys
from pathlib import Path

from trace_vr import base_prompt


def load(runs_dir: Path):
    scans = {}
    for v in base_prompt.VARIANTS:
        p = runs_dir / base_prompt.run_name(v) / "token_budget_dev.json"
        if not p.exists():
            raise SystemExit("missing %s: all variants are needed before one is chosen" % p)
        scans[v] = json.loads(p.read_text())
    return scans


def markdown(choice) -> str:
    lines = ["# Frozen-base prompt variant (chosen on dev)", "",
             "Generated by `scripts/base_prompt_choice.py`; rule in `src/trace_vr/base_prompt.py`.", "",
             "%d dev roots, %d samples, long limit %d new tokens. Added sentence: \"%s\"" % (
                 choice["eval_root_graphs"], choice["samples"], choice["run_limit"], choice["direct_sentence"]), "",
             "| variant | token limit | strict non-edit macro | lenient | max truncation |", "|---|---|---|---|---|"]
    for v, e in choice["variants"].items():
        lenient = "n/a" if e["non_edit_macro_lenient"] is None else "%.4f" % e["non_edit_macro_lenient"]
        lines.append("| %s%s | %d | %.4f | %s | %.3f |" % (v, " (chosen)" if v == choice["chosen"] else "", e["chosen_limit"],
                                                       e["non_edit_macro"], lenient, e["max_truncation_rate"]))
    return "\n".join(lines) + "\n"


def main(argv):
    out = out_md = None
    if "--out" in argv:
        i = argv.index("--out"); out = Path(argv[i + 1]); argv = argv[:i] + argv[i + 2:]
    if "--out-md" in argv:
        i = argv.index("--out-md"); out_md = Path(argv[i + 1]); argv = argv[:i] + argv[i + 2:]
    (runs_dir,) = argv
    try:
        choice = base_prompt.choose(load(Path(runs_dir)))
    except ValueError as e:
        raise SystemExit(str(e))
    if out:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(choice, indent=2) + "\n")
    if out_md:
        out_md.parent.mkdir(parents=True, exist_ok=True)
        out_md.write_text(markdown(choice))
    print("BASE-PROMPT " + json.dumps({"chosen": choice["chosen"], "limit": choice["chosen_limit"],
                                       "macro": {v: e["non_edit_macro"] for v, e in choice["variants"].items()}}), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:])
