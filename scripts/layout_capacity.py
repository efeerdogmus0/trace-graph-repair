"""Layout acceptance per family, node count and style at the build's image size.

Checks, before the main build, whether drawings of 13-18-node graphs can be laid out at
512 px under the same checks the builder uses (`layout.find_layout`), and whether the
rendered pixels pass `render.image_checks`. Independent seeds; no data build, no labels.

Usage: python scripts/layout_capacity.py [draws_per_cell] [families] [nmin] [nmax] [styles] [out.md]
"""
from __future__ import annotations

import json
import sys
import time
from typing import Dict, List

from trace_vr import families, layout, render
from trace_vr.rng import Rng
from trace_vr.styles import get_style
from trace_vr.tasks import LABEL_ALPHABET

SIZE = 512


def scan_cell(family: str, n: int, sid: str, k: int, render_check: bool = True, budget: int = 180) -> Dict:
    style = get_style(sid)
    ok = pixel_bad = 0
    crossings: List[int] = []
    edges_ok: List[int] = []
    edges_rej: List[int] = []
    fails: Dict[str, int] = {}
    names: Dict[str, int] = {}
    t0 = time.time()
    for i in range(k):
        rng = Rng("layout-capacity", family, n, sid, i)
        g = families.generate(family, n, rng.child("graph"))
        lay, f = layout.find_layout(g, style, rng.child("layout"), SIZE, budget=budget)
        for key, v in f.items():
            fails[key] = fails.get(key, 0) + v
        if lay is None:
            edges_rej.append(len(g.edges))
            continue
        edges_ok.append(len(g.edges))
        ok += 1
        crossings.append(lay.crossings)
        names[lay.layout_name] = names.get(lay.layout_name, 0) + 1
        if render_check:
            labels = rng.child("labels").sample(LABEL_ALPHABET, n)
            img = render.draw_diagram(lay.pos, labels, lay.routes, style, SIZE)
            nodes = {labels[j]: list(lay.pos[j]) for j in range(n)}
            edges = [{"src": labels[u], "dst": labels[v], "points": lay.routes[(u, v)]} for (u, v) in sorted(lay.routes)]
            if render.image_checks(img, style, nodes, edges):
                pixel_bad += 1
    secs = time.time() - t0
    def _mean(xs):
        return round(sum(xs) / float(len(xs)), 2) if xs else None
    return {"family": family, "n": n, "style": sid, "draws": k, "budget": budget, "accepted": ok,
            "mean_edges_accepted": _mean(edges_ok), "mean_edges_rejected": _mean(edges_rej),
            "accept_rate": round(ok / float(k), 3), "pixel_problems": pixel_bad,
            "mean_crossings": round(sum(crossings) / len(crossings), 2) if crossings else None,
            "max_crossings": max(crossings) if crossings else None,
            "layouts": names, "fail_reasons": fails, "s_per_graph": round(secs / k, 3)}


def main(argv: List[str]) -> None:
    k = int(argv[1]) if len(argv) > 1 else 20
    fams = argv[2].split(",") if len(argv) > 2 else ["layered_dag", "tree_plus", "sparse_random"]
    nmin = int(argv[3]) if len(argv) > 3 else 13
    nmax = int(argv[4]) if len(argv) > 4 else 18
    styles = argv[5].split(",") if len(argv) > 5 else ["a", "b", "c"]
    out = argv[6] if len(argv) > 6 else None
    rows = []
    t0 = time.time()
    for fam in fams:
        for n in range(max(nmin, families.MIN_NODES[fam]), nmax + 1):
            for sid in styles:
                r = scan_cell(fam, n, sid, k)
                rows.append(r)
                print(json.dumps(r), flush=True)
    secs = time.time() - t0
    if out:
        lines = [
            "# Layout acceptance per family, node count and style (%d px)" % SIZE,
            "",
            "Generated by `scripts/layout_capacity.py %d %s %d %d %s` (%.0f s). Each cell: %d graphs"
            % (k, ",".join(fams), nmin, nmax, ",".join(styles), secs, k),
            "drawn with independent seeds and passed to the builder's `layout.find_layout`; accepted",
            "layouts are rendered and checked with `render.image_checks`. `accept` is the share of",
            "graphs for which any layout passed; a rejected root is redrawn by the builder, so a low",
            "rate costs build time and biases accepted roots toward easier-to-draw topologies.",
            "",
            "| family | n | style | accept | pixel problems | mean / max crossings | s/graph | main fail reasons |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for r in rows:
            top = sorted(r["fail_reasons"].items(), key=lambda kv: -kv[1])[:2]
            lines.append("| %s | %d | %s | %d/%d | %d | %s / %s | %.2f | %s |" % (
                r["family"], r["n"], r["style"], r["accepted"], r["draws"], r["pixel_problems"],
                r["mean_crossings"], r["max_crossings"], r["s_per_graph"],
                ", ".join("%s %d" % kv for kv in top) or "-"))
        with open(out, "w", encoding="utf-8") as fh:
            fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv)
