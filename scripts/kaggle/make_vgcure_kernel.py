"""Write a Kaggle script kernel that evaluates trained adapters on the pre-registered VGCure subset (M7).

Usage: python scripts/kaggle/make_vgcure_kernel.py <job> (--after-final-evaluation | --dev) [--from-head] <spec> [<spec> ...]
  spec = <source_job>:<run>                      direct answers with runs/<run>/adapter from kernel <source_job>
       | <source_job>:<run>:parse=<parser_run>   arm E: parser adapter runs/<parser_run>/adapter + exact solver
       | base                                    frozen base model, no adapter
  e.g. jobV1 --after-final-evaluation job11:pilot3_B_kaggle job20:pilot3_D_kaggle job13:pilot3_E:parse=pilot3_C_desc

docs/external_eval.md fixes VGCure as evaluated once, after the locked test, so the builder refuses without
--after-final-evaluation. VGCure files are downloaded on Kaggle's side (scripts/vgcure_prepare.py checks the
zip hashes and the subset digest); nothing from VGCure is embedded or committed. Every adapter is attached
through `kernel_sources` and checked against its sha256 in runs/kaggle_artifacts.json, as in make_final_kernel.py.
"""
import base64, hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "scripts" / "kaggle"))
import build_payload  # noqa: E402
import make_kernel as mk  # noqa: E402
from make_final_kernel import adapter_sha  # noqa: E402

SUBSET_RECORD = "reports/external/vgcure_subset.json"

KERNEL = r'''# TRACE VGCure external evaluation {job}. Generated by scripts/kaggle/make_vgcure_kernel.py
# payload sha256 {sha}
import base64, glob, hashlib, io, os, shutil, subprocess, sys, tarfile
PAYLOAD = "{b64}"
data = base64.b64decode(PAYLOAD)
assert hashlib.sha256(data).hexdigest() == "{sha}"
home, work, vg = "/tmp/trace", "/kaggle/working", "/tmp/vgcure"
os.makedirs(home, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(data), mode="r:gz").extractall(home)
os.makedirs(work + "/runs", exist_ok=True)
if not os.path.islink(home + "/runs"):
    os.symlink(work + "/runs", home + "/runs")
def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()
ARMS = {arms}   # (run, adapter_run or None, adapter sha256 or None, parse_solve)
for run, adapter_run, want, _ in ARMS:
    if adapter_run is None:
        continue
    dst = work + "/runs/%s/adapter" % adapter_run
    if os.path.exists(dst):
        continue
    hits = [p for p in glob.glob("/kaggle/input/**/runs/%s/adapter/adapter_model.safetensors" % adapter_run, recursive=True)
            if sha_file(p) == want]
    assert hits, "adapter of %s with the recorded sha256 not found under /kaggle/input" % adapter_run
    shutil.copytree(os.path.dirname(hits[0]), dst)
    print("adapter ok", adapter_run, hits[0])
subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv", shell=True)
subprocess.run("pip -q install {pins} 2>&1 | tail -3", shell=True)
subprocess.run("pip -q uninstall -y torchao 2>&1 | tail -1", shell=True)
env = dict(os.environ, PYTHONPATH=home + "/src", CUDA_VISIBLE_DEVICES="0", PYTHONUNBUFFERED="1",
           TRACE_VGCURE_RECORD="{record}")
log = open(work + "/{job}.log", "w")
def run(cmd):
    p = subprocess.Popen(cmd, cwd=home, env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        if "Loading weights" in line:
            continue
        print(line, end=""); log.write(line); log.flush()
    return p.wait()
rc = run([sys.executable, "scripts/vgcure_prepare.py", vg])
for name, adapter_run, _, parse in ARMS:
    if rc:
        break
    out = work + "/runs/" + name
    if os.path.exists(out + "/metrics_vgcure.json"):
        continue
    adapter = (work + "/runs/%s/adapter" % adapter_run) if adapter_run else "none"
    rc = run([sys.executable, "scripts/eval_vgcure.py", vg, out, adapter] + (["--parse-solve"] if parse else []))
print("KERNEL-EXIT", rc)
sys.exit(rc)
'''


def parse_spec(spec):
    """-> (source_job or None, run_name, adapter_run or None, parse_solve)."""
    if spec == "base":
        return None, "base_A", None, False
    parts = spec.split(":")
    if len(parts) not in (2, 3) or not parts[1].startswith("pilot3_"):
        raise SystemExit("bad spec %r\n%s" % (spec, __doc__))
    source, run = parts[0], parts[1]
    if len(parts) == 3:
        if not parts[2].startswith("parse=pilot3_") or parts[2][6:] == run:
            raise SystemExit("bad parse spec %r" % spec)
        return source, run, parts[2][6:], True
    return source, run, run, False


def main(argv):
    dev = "--dev" in argv   # exploratory dev subset (disjoint graphs); the pre-registered subset stays guarded
    record = "reports/external/vgcure_dev_subset.json" if dev else SUBSET_RECORD
    if not dev and "--after-final-evaluation" not in argv:
        raise SystemExit("refusing: VGCure is evaluated once, after the locked test; pass --after-final-evaluation\n" + __doc__)
    from_head = "--from-head" in argv
    unknown = [a for a in argv if a.startswith("--") and a not in ("--after-final-evaluation", "--from-head", "--dev")]
    pos = [a for a in argv if not a.startswith("--")]
    if unknown or len(pos) < 2:
        raise SystemExit("usage error %s\n%s" % (unknown, __doc__))
    job, specs = pos[0], [parse_spec(s) for s in pos[1:]]
    names = [s[1] for s in specs]
    if len(set(names)) != len(names):
        raise SystemExit("each run may appear once")
    arms = [(run, adapter_run, adapter_sha(source, adapter_run) if adapter_run else None, parse)
            for source, run, adapter_run, parse in specs]
    sources = sorted({"%s/trace-%s" % (mk.OWNER, s[0].lower()) for s in specs if s[0]})
    # the pre-registered selection record travels with the code (prepare/eval refuse a different subset)
    build_payload.INCLUDE = [i for i in build_payload.INCLUDE if i != "assets"] + [record]
    data = build_payload.build(mk.head_tree() if from_head else ROOT)
    sha = hashlib.sha256(data).hexdigest()
    out = ROOT / "dist" / "kaggle" / job
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(KERNEL.format(job=job, sha=sha, b64=base64.b64encode(data).decode(),
                                                 arms=repr(arms), pins=mk.PINS, record=record))
    meta = {"id": "%s/trace-%s" % (mk.OWNER, job.lower()), "title": "trace %s" % job, "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_tpu": False, "enable_internet": True,
            "dataset_sources": [], "kernel_sources": sources, "competition_sources": [], "model_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print("%s  arms %s  payload sha256 %s  from_head=%s" % (out, names, sha, from_head))
    return out


if __name__ == "__main__":
    main(sys.argv[1:])
