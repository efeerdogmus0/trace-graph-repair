"""Write a Kaggle script kernel that runs one scripts/colab/job.sh job on a T4.

Usage: python scripts/kaggle/make_kernel.py <job> <arm> <roots:mode>[,<roots:mode>...] [--seed N] [--from-head]
  e.g. job11 B 200:image,100:edges (one training, then each evaluation in order);
  --seed N sets TRACE_SEED for job.sh (pre-registered seeds only: 3407, 2027, 9173; run dir pilot3_<arm>_s<N>);
  arm E runs scripts/colab/job_e.sh (train C_desc, then parse-and-solve; mode must be image)
  arm A runs scripts/colab/base_prompt.sh (frozen base under each prompt variant on <roots> dev roots, no
  training; one <roots>:image entry, default seed only), e.g. jobA1 A 30:image
  -> dist/kaggle/<job>/{kernel.py, kernel-metadata.json}; then
     kaggle kernels push -p dist/kaggle/<job> --accelerator NvidiaTeslaT4

The code payload (scripts/build_payload.py, byte-reproducible) is embedded base64 in kernel.py,
so no Kaggle dataset is needed. --from-head packs the last git commit instead of the working tree
(the autopilot may have uncommitted edits). The kernel regenerates the data (job.sh asserts the
content digest), pins transformers/peft to the versions used on Colab, and keeps runs/ under
/kaggle/working so the adapter, metrics and predictions survive as kernel output.
Private kernel, internet on (Hub download of the pinned base revision). No secrets are embedded.
"""
import base64, hashlib, io, json, subprocess, sys, tarfile, tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
import build_payload  # noqa: E402
from build_payload import build  # noqa: E402

# Fonts are not embedded (Kaggle rejected a 2.2 MB script): the kernel links matplotlib's bundled
# DejaVu files (where assets/fonts was copied from, docs/environment.md) and checks these hashes.
FONT_SHA = {f.name: hashlib.sha256(f.read_bytes()).hexdigest()
            for f in sorted((ROOT / "assets" / "fonts").glob("*.ttf"))}

OWNER = "yiitefeerdomu"
SEEDS = (3407, 2027, 9173)   # docs/protocol.md, fixed before any seed run
DEFAULT_SEED = 3407
PINS = "transformers==5.22.2 peft==0.21.2"   # docs: runs/a0_smoke_t4/metrics.json (Colab T4)

KERNEL = r'''# TRACE job {job}: arm={arm} seed={seed} evals={evals}. Generated by scripts/kaggle/make_kernel.py
# payload sha256 {sha}
import base64, hashlib, io, os, subprocess, sys, tarfile
PAYLOAD = "{b64}"
data = base64.b64decode(PAYLOAD)
assert hashlib.sha256(data).hexdigest() == "{sha}"
home, work = "/tmp/trace", "/kaggle/working"
os.makedirs(home, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(data), mode="r:gz").extractall(home)
os.makedirs(work + "/runs", exist_ok=True)
if not os.path.islink(home + "/runs"):
    os.symlink(work + "/runs", home + "/runs")
sh = lambda c: subprocess.run(c, shell=True, check=False)
import glob, matplotlib
fonts = home + "/assets/fonts"; os.makedirs(fonts, exist_ok=True)
for name, want in {fonts_sha}.items():
    hits = [f for f in glob.glob(os.path.dirname(matplotlib.__file__) + "/mpl-data/fonts/ttf/" + name)
            if hashlib.sha256(open(f, "rb").read()).hexdigest() == want]
    assert hits, "font %s with the laptop's sha256 not found in matplotlib" % name
    if not os.path.exists(fonts + "/" + name):
        os.symlink(hits[0], fonts + "/" + name)
print("fonts ok", len({fonts_sha}))
sh("nvidia-smi --query-gpu=name,memory.total --format=csv")
sh("pip -q install {pins} 2>&1 | tail -3")
env = dict(os.environ, TRACE_HOME=home, TRACE_TMP="/tmp", CUDA_VISIBLE_DEVICES="0",
           PYTHONUNBUFFERED="1", TRACE_SEED="{seed}")
log = open(work + "/{job}.log", "w")
rc = 0
for roots, mode in {evals}:   # job.sh skips training once train_summary.json exists
    cmd = ([home + "/scripts/colab/job_e.sh", "{job}", roots] if "{arm}" == "E"
           else [home + "/scripts/colab/base_prompt.sh", "{job}", roots] if "{arm}" == "A"
           else [home + "/scripts/colab/job.sh", "{job}", "{arm}", roots, mode])
    p = subprocess.Popen(["bash"] + cmd,
                         env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
    for line in p.stdout:
        print(line, end=""); log.write(line); log.flush()
    rc = p.wait()
    if rc:
        break
if rc == 0:   # optimizer/resume state is only needed inside a run; keep outputs small
    import shutil
    for d in glob.glob(work + "/runs/*/ckpt"):
        shutil.rmtree(d)
print("KERNEL-EXIT", rc)
sys.exit(rc)
'''


def head_tree() -> Path:
    tmp = Path(tempfile.mkdtemp(prefix="trace_head_"))
    arc = subprocess.run(["git", "-C", str(ROOT), "archive", "HEAD"], check=True, capture_output=True).stdout
    tarfile.open(fileobj=io.BytesIO(arc)).extractall(tmp)
    return tmp


def main(argv):
    from_head = "--from-head" in argv
    argv = [a for a in argv if a != "--from-head"]
    seed = DEFAULT_SEED
    if "--seed" in argv:
        i = argv.index("--seed"); seed = int(argv[i + 1]); argv = argv[:i] + argv[i + 2:]
    if seed not in SEEDS:
        raise SystemExit("seed %d is not pre-registered (docs/protocol.md: %s)" % (seed, SEEDS))
    job, arm, spec = argv
    evals = [tuple(x.split(":")) for x in spec.split(",")]
    assert all(len(e) == 2 and e[0].isdigit() for e in evals), spec
    if arm == "A" and (len(evals) != 1 or evals[0][1] != "image" or seed != DEFAULT_SEED):
        raise SystemExit("arm A (frozen-base prompt variants) takes one <roots>:image entry and no --seed")
    build_payload.INCLUDE = [i for i in build_payload.INCLUDE if i != "assets"]
    data = build(head_tree() if from_head else ROOT)
    sha = hashlib.sha256(data).hexdigest()
    out = ROOT / "dist" / "kaggle" / job
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(KERNEL.format(job=job, arm=arm, seed=seed, evals=repr(evals), sha=sha,
                                                 b64=base64.b64encode(data).decode(), pins=PINS, fonts_sha=repr(FONT_SHA)))
    slug = "trace-" + job.lower()
    meta = {"id": f"{OWNER}/{slug}", "title": f"trace {job}", "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_tpu": False, "enable_internet": True,
            "dataset_sources": [], "kernel_sources": [], "competition_sources": [], "model_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print(f"{out}  seed {seed}  payload {len(data)} bytes sha256 {sha}  from_head={from_head}")


if __name__ == "__main__":
    main(sys.argv[1:])
