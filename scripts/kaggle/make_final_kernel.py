"""Write a Kaggle script kernel that runs scripts/colab/final_eval.sh on an adapter trained by an earlier kernel.

Usage: python scripts/kaggle/make_final_kernel.py <job> <source_job> <run> --final-evaluation [--from-head]
                                                  [--parse-solve=<parser_run>]
       python scripts/kaggle/make_final_kernel.py <job> none A --final-evaluation --base-prompt [--from-head]
  e.g. jobF1 job14 pilot3_B_s2027 --final-evaluation
       jobF5 job13 pilot3_E --final-evaluation --parse-solve=pilot3_C_desc   (arm E: parser adapter + exact solver)
       jobF13 none A --final-evaluation --base-prompt   (arm A: frozen base, no adapter; the prompt variant and the
                                                         token limit are read from reports/pilot/base_prompt.json,
                                                         the dev choice, and cannot be given by hand)
  -> dist/kaggle/<job>/{kernel.py, kernel-metadata.json}; push like make_kernel.py.
  --owner=<kaggle user>: the kernel is created under a collaborator's account (his own weekly quota). Only the
  kernel id changes; the adapter still comes from the project account's source kernel, which must be shared
  with that user, and is still checked against the recorded sha256. Output goes to dist/kaggle/<owner>/<job>/.
  --adapter-dataset=<user>/<slug>: attach a private dataset holding runs/<run>/adapter/ instead of the source
  kernel (a copy of the downloaded adapter uploaded to the collaborator's account); same sha256 check.

The locked test splits may be scored once, after every decision is frozen on dev (brief section 19, M6),
so the builder refuses without --final-evaluation. The adapter is not embedded: the kernel attaches the
source kernel's output (`kernel_sources`), finds <run>/adapter there and checks adapter_model.safetensors
against the sha256 recorded for it in runs/kaggle_artifacts.json, so the evaluated adapter is provably the
one the dev numbers came from. Same payload, font check and version pins as make_kernel.py.
"""
import base64, hashlib, json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))
sys.path.insert(0, str(ROOT / "scripts" / "kaggle"))
import build_payload  # noqa: E402
import make_kernel as mk  # noqa: E402

ADAPTER_BLOCK = r'''hits = [p for p in glob.glob("/kaggle/input/**/{adapter_glob}{adapter_run}/adapter/adapter_model.safetensors", recursive=True)
        if sha_file(p) == "{adapter_sha}"]
assert hits, "adapter of {adapter_run} with the recorded sha256 not found under /kaggle/input"
dst = work + "/runs/{adapter_run}/adapter"
if not os.path.exists(dst):
    shutil.copytree(os.path.dirname(hits[0]), dst)
print("adapter ok", hits[0])
'''
NO_ADAPTER_BLOCK = 'print("no adapter: frozen base, prompt variant {variant}, limit {limit}")\n'

# Run inside the kernel, after the pins are installed, in a child process: one ENV-SUMMARY line in the kernel's
# own stdout (trace-<job>.log), never in <job>.log, which collect_final.py checks. A missing module is recorded
# as null, so the same code runs on a machine without torch. Read back with scripts/kaggle/kernel_env.py.
ENV_PROBE = r"""import importlib, json, os, platform, sys
out = {"python": platform.python_version(), "platform": platform.platform()}
for m in ("torch", "transformers", "peft", "accelerate", "numpy", "PIL", "matplotlib", "safetensors", "tokenizers"):
    try:
        out[m] = importlib.import_module(m).__version__
    except Exception:
        out[m] = None
try:
    import torch
    out["cuda"] = torch.version.cuda
    out["cudnn"] = torch.backends.cudnn.version()
    out["gpus"] = [torch.cuda.get_device_name(i) for i in range(torch.cuda.device_count())]
except Exception:
    out["cuda"] = out["cudnn"] = out["gpus"] = None
out["image"] = os.environ.get("KAGGLE_DOCKER_IMAGE")
print("ENV-SUMMARY " + json.dumps(out, sort_keys=True))
"""

KERNEL = r'''# TRACE FINAL evaluation {job}: run={run} adapter {adapter_run} from {owner}/trace-{source}. Generated by scripts/kaggle/make_final_kernel.py
# payload sha256 {sha}
import base64, glob, hashlib, io, os, shutil, subprocess, sys, tarfile
PAYLOAD = "{b64}"
data = base64.b64decode(PAYLOAD)
assert hashlib.sha256(data).hexdigest() == "{sha}"
home, work = "/tmp/trace", "/kaggle/working"
os.makedirs(home, exist_ok=True)
tarfile.open(fileobj=io.BytesIO(data), mode="r:gz").extractall(home)
os.makedirs(work + "/runs", exist_ok=True)
if not os.path.islink(home + "/runs"):
    os.symlink(work + "/runs", home + "/runs")
def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()
{adapter_block}import matplotlib
fonts = home + "/assets/fonts"; os.makedirs(fonts, exist_ok=True)
for name, want in {fonts_sha}.items():
    f_hits = [f for f in glob.glob(os.path.dirname(matplotlib.__file__) + "/mpl-data/fonts/ttf/" + name)
              if sha_file(f) == want]
    assert f_hits, "font %s with the laptop's sha256 not found in matplotlib" % name
    if not os.path.exists(fonts + "/" + name):
        os.symlink(f_hits[0], fonts + "/" + name)
print("fonts ok", len({fonts_sha}))
subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv", shell=True)
subprocess.run("pip -q install {pins} 2>&1 | tail -3", shell=True)
subprocess.run([sys.executable, "-c", {env_probe}])
env = dict(os.environ, TRACE_HOME=home, TRACE_TMP="/tmp", CUDA_VISIBLE_DEVICES="0", PYTHONUNBUFFERED="1")
log = open(work + "/{job}.log", "w")
p = subprocess.Popen(["bash", home + "/scripts/colab/final_eval.sh", "{job}", "{run}", "--final-evaluation"{mode_arg}],
                     env=env, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
for line in p.stdout:
    print(line, end=""); log.write(line); log.flush()
rc = p.wait()
print("KERNEL-EXIT", rc)
sys.exit(rc)
'''


def adapter_sha(source_job, run, manifest=ROOT / "runs/kaggle_artifacts.json"):
    want = "%s/runs/%s/adapter/adapter_model.safetensors" % (source_job, run)
    for f in json.loads(Path(manifest).read_text())["files"]:
        if f["path"] == want:
            return f["sha256"]
    raise SystemExit("no sha256 for %s in %s (download the output and run artifact_manifest.py first)"
                     % (want, manifest))


CHOICE = ROOT / "reports/pilot/base_prompt.json"


def base_choice(path=None):
    """(variant, token limit) of the frozen base as chosen on dev by scripts/base_prompt_choice.py."""
    path = Path(path or CHOICE)
    if not path.exists():
        raise SystemExit("missing %s: choose the frozen-base prompt on dev first (jobA1, base_prompt_choice.py)" % path)
    c = json.loads(path.read_text())
    sys.path.insert(0, str(ROOT / "src"))
    from trace_vr import base_prompt
    if c.get("split") != "dev" or c.get("chosen") not in base_prompt.VARIANTS or not isinstance(c.get("chosen_limit"), int):
        raise SystemExit("%s is not a dev choice with a variant and an integer limit" % path)
    if c["chosen_limit"] != c["variants"][c["chosen"]]["chosen_limit"]:
        raise SystemExit("%s: chosen_limit does not match the chosen variant's entry" % path)
    return c["chosen"], c["chosen_limit"]


def main(argv):
    if "--final-evaluation" not in argv:
        raise SystemExit("refusing: the locked test splits are scored once; pass --final-evaluation\n" + __doc__)
    from_head = "--from-head" in argv
    parse = [a for a in argv if a.startswith("--parse-solve=")]
    unknown = [a for a in argv if a.startswith("--") and a not in ("--final-evaluation", "--from-head", "--base-prompt") and a not in parse
               and not a.startswith("--owner=") and not a.startswith("--adapter-dataset=")]
    if unknown or len(parse) > 1 or len([a for a in argv if a.startswith("--owner=")]) > 1:
        raise SystemExit("unknown or repeated option %s\n%s" % (unknown or parse, __doc__))
    pos = [a for a in argv if not a.startswith("--")]
    if len(pos) != 3:
        raise SystemExit(__doc__)
    job, source, run = pos
    base = "--base-prompt" in argv
    if base != (source == "none") or base != (run == "A") or (base and parse):
        raise SystemExit("arm A is built with exactly: <job> none A --final-evaluation --base-prompt\n" + __doc__)
    if not base and not run.startswith("pilot3_"):
        raise SystemExit("run must be a pilot3_* run directory name")
    adapter_run, mode_arg = run, ""
    if base:
        variant, limit = base_choice()
        run, adapter_run = "base_prompt_%s" % variant, "none"
        mode_arg = ', "--base-prompt=%s:%d"' % (variant, limit)
        a_sha, adapter_block = "none", NO_ADAPTER_BLOCK.format(variant=variant, limit=limit)
    elif parse:
        adapter_run = parse[0].split("=", 1)[1]
        if not adapter_run.startswith("pilot3_") or adapter_run == run:
            raise SystemExit("--parse-solve needs a pilot3_* parser run different from <run>")
        mode_arg = ', "--parse-solve=%s"' % adapter_run
    if not base:
        a_sha = adapter_sha(source, adapter_run)
        adapter_block = None  # filled in once the adapter source (kernel or dataset) is known
    build_payload.INCLUDE = [i for i in build_payload.INCLUDE if i != "assets"]
    data = build_payload.build(mk.head_tree() if from_head else ROOT)
    sha = hashlib.sha256(data).hexdigest()
    owner_opt = [a for a in argv if a.startswith("--owner=")]
    kernel_owner = owner_opt[0].split("=", 1)[1] if owner_opt else mk.OWNER
    if not kernel_owner or "/" in kernel_owner or " " in kernel_owner:
        raise SystemExit("--owner needs a Kaggle user name")
    ds_opt = [a.split("=", 1)[1] for a in argv if a.startswith("--adapter-dataset=")]
    if len(ds_opt) > 1 or any(d.count("/") != 1 for d in ds_opt) or (ds_opt and base):
        raise SystemExit("--adapter-dataset needs one <user>/<slug> and an adapter run")
    if not base:
        # a kernel output keeps runs/<run>/; a Kaggle dataset uploaded from runs/ drops that top folder
        adapter_block = ADAPTER_BLOCK.format(adapter_run=adapter_run, adapter_sha=a_sha,
                                             adapter_glob="" if ds_opt else "runs/")
    out = ROOT / "dist" / "kaggle" / job if kernel_owner == mk.OWNER else ROOT / "dist" / "kaggle" / kernel_owner / job
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(KERNEL.format(job=job, run=run, adapter_run=adapter_run, mode_arg=mode_arg, source=source, owner=mk.OWNER, sha=sha,
                                                 b64=base64.b64encode(data).decode(), adapter_block=adapter_block,
                                                 pins=mk.PINS, fonts_sha=repr(mk.FONT_SHA), env_probe=repr(ENV_PROBE)))
    meta = {"id": "%s/trace-%s" % (kernel_owner, job.lower()), "title": "trace %s" % job, "code_file": "kernel.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_tpu": False, "enable_internet": True,
            "dataset_sources": ds_opt, "kernel_sources": [] if base or ds_opt else ["%s/trace-%s" % (mk.OWNER, source.lower())],
            "competition_sources": [], "model_sources": []}
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    print("%s  run %s  adapter %s sha256 %s  payload sha256 %s  from_head=%s" % (out, run, adapter_run, a_sha, sha, from_head))
    return out


if __name__ == "__main__":
    main(sys.argv[1:])
