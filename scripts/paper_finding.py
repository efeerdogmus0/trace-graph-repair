"""Paper abstract and intro finding paragraph, generated from the primary statistic (CPU only).

Usage: python scripts/paper_finding.py [--primary reports/final/final_primary.json]
                                       [--out-dir reports/final]

Writes `abstract.tex` and `intro_finding.tex` into --out-dir. paper/main.tex and paper/sections/intro.tex
\\input them through \\IfFileExists, so until this script has run the paper keeps its "no result claimed" text.

Rule `finding-v1`, fixed 2026-11-20 before any locked-test number was read (PLAN items 37 and 43 left the
abstract, conclusion and intro finding paragraph open "after the primary reading"; writing the wording after the
reading would let the result choose the words):
- the only input is final_primary.json; the reading of D against the recorded reference is taken exactly as
  scripts/result_summary.py takes it (same refusal rules, imported), and selects one of five fixed sentences.
- fixed parts: one benchmark sentence (true whatever the result), the numbers sentence, the pilot-scale sentence
  (tested against limitations.tex). Secondary facts (task_drop, splits, E - D, C - reference) are not in the abstract;
  the intro paragraph points to the test-results section for them.
- refuses and writes nothing while the primary file is missing; do not edit the sentences after the reading."""
import importlib.util, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RULE = "finding-v1"
_spec = importlib.util.spec_from_file_location("result_summary", ROOT / "scripts/result_summary.py")
rs = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(rs)
READINGS = rs.READINGS
PRIMARY = rs.PRIMARY

BENCH = ("We introduce a procedural benchmark of drawn directed graphs with exact labels, a verifier that accepts every "
         "optimal repair edit, and answer-flipping twins that cap any image-blind predictor at $0.50$ per task, and use it "
         "to ask whether training a small vision-language model to repair a drawing teaches it to answer reachability "
         "and edge-criticality questions it was never trained on.")
FINDING = {
    "positive_clear": "Repair training (arm~D) beat the reference fine-tuning arm by a clear margin on the pre-registered "
                      "six-cell statistic, with every seed pointing the same way.",
    "positive": "Repair training (arm~D) beat the reference fine-tuning arm on the pre-registered six-cell statistic, "
                "but by less than the pre-registered clear margin of $0.05$.",
    "negative": "Repair training (arm~D) did worse than the reference fine-tuning arm on the pre-registered six-cell "
                "statistic; the hypothesis is not supported at this scale.",
    "inconclusive": "The pre-registered six-cell statistic does not separate repair training (arm~D) from the reference "
                    "fine-tuning arm: the interval or the seeds disagree, so we claim no effect in either direction.",
    "incomplete_seeds": "The comparison of repair training (arm~D) with the reference arm could not be read under the "
                        "pre-registered rule because a seed is missing; we make no claim.",
}
SCALE = ("This is a pilot-scale study: all adapters were trained on $512$ synthetic root graphs with one 2B base model "
         "(Qwen3.5-2B, LoRA), and nothing here measures real diagrams.")


def _num(x):
    return "$%+.3f$" % x


def numbers(ref, d):
    e = d["diff"][PRIMARY]
    n = len(d.get("seed_matched") or {})
    return ("On the locked test the difference D$-$%s is %s (95\\%% interval [%s, %s], mean of %d seed%s)."
            % (ref, _num(e["point"]), _num(e["lo"]), _num(e["hi"]), n, "" if n == 1 else "s"))


def render(t):
    ref, d, _diffs, _arms = rs.parts(t)
    tag = "%% generated by scripts/paper_finding.py, rule %s, from reports/final/final_primary.json; do not edit\n" % RULE
    abstract = tag + " ".join([BENCH, FINDING[d["reading"]], numbers(ref, d), SCALE]) + "\n"
    intro = tag + ("\\paragraph{Main finding.} " + " ".join([FINDING[d["reading"]], numbers(ref, d), SCALE])
                   + " Per-split, per-task and secondary comparisons are in Section~\\ref{sec:test-results}.\n")
    return {"abstract.tex": abstract, "intro_finding.tex": intro}


def main(argv):
    opts = {"primary": str(ROOT / "reports/final/final_primary.json"), "out-dir": str(ROOT / "reports/final")}
    args = list(argv)
    for key in list(opts):
        if "--" + key in args:
            i = args.index("--" + key); opts[key] = args[i + 1]; del args[i:i + 2]
    if args:
        raise SystemExit(__doc__)
    texts = render(rs.load(opts["primary"]))
    out = Path(opts["out-dir"]); out.mkdir(parents=True, exist_ok=True)
    for name, text in texts.items():
        (out / name).write_text(text)
        print("wrote %s" % (out / name))


if __name__ == "__main__":
    main(sys.argv[1:])
