"""Seed-pooled dev table from saved flag files (CPU only). Rules: src/trace_vr/seeds.py.

Usage:
  python scripts/seed_table.py <manifest> --ref LABEL LABEL@SEED=flags.json [...] [--out-json f] [--out-md f] [--out-tex f]
         [--boot 2000]

Every flag file must cover the same split, root graphs, sample set and dataset build. Seeds must be
pre-registered (3407, 2027, 9173). A label may appear with one to three seeds."""
import json, sys
from pathlib import Path
from trace_vr import arms as arms_mod, bootstrap, dataset, seeds

MACRO = bootstrap.MACRO


def parse(argv):
    args = list(argv)
    opts = {"boot": 2000, "ref": None, "out-json": None, "out-md": None, "out-tex": None}
    for key in list(opts):
        flag = "--" + key
        if flag in args:
            i = args.index(flag); opts[key] = args[i + 1]; del args[i:i + 2]
    if not args or opts["ref"] is None:
        raise SystemExit(__doc__)
    manifest, entries = args[0], []
    for a in args[1:]:
        if "=" not in a or "@" not in a.split("=", 1)[0]:
            raise SystemExit("expected LABEL@SEED=path, got %r" % a)
        head, path = a.split("=", 1)
        label, s = head.rsplit("@", 1)
        s = int(s)
        if s not in seeds.PREREGISTERED_SEEDS:
            raise SystemExit("seed %d is not pre-registered" % s)
        if (label, s) in [(e[0], e[1]) for e in entries]:
            raise SystemExit("duplicate %s@%d" % (label, s))
        entries.append((label, s, Path(path)))
    if opts["ref"] not in {e[0] for e in entries}:
        raise SystemExit("--ref %s is not one of the arms" % opts["ref"])
    return manifest, entries, opts


def build(manifest, entries, ref, n_boot):
    man, _, by_split, _ = dataset.load_dataset(Path(manifest))
    key, payloads = None, []
    for label, s, path in entries:
        p = json.loads(path.read_text())
        if p["content_digest"] != man["content_digest"]:
            raise SystemExit("%s comes from a different dataset build" % path)
        k = (p["split"], p["eval_root_graphs"], p.get("sample_set", "main"))
        if key is None:
            key = k
        elif k != key:
            raise SystemExit("%s covers different samples %s than %s" % (path, k, key))
        if p.get("missing_responses"):
            raise SystemExit("%s has %d missing responses" % (path, p["missing_responses"]))
        payloads.append((label, s, path, p))
    rows = arms_mod.eval_samples(by_split[key[0]], key[1])
    flags = {}
    for label, s, _, p in payloads:
        flags.setdefault(label, {})[s] = bootstrap.decode_flags(rows, p)
    t = seeds.pooled_bootstrap(rows, flags, ref, n_boot=n_boot)
    t.update({"split": key[0], "sample_set": key[2], "content_digest": man["content_digest"],
              "files": [{"label": l, "seed": s, "file": str(path), "predictions_sha256": p.get("predictions_sha256")}
                        for l, s, path, p in payloads]})
    return t


def markdown(t):
    lines = ["Dev split `%s`, %d root graphs, %s samples; pooled = mean over seeds on the same resampled roots "
             "(%d replicates, 95%%, root sampling only). Rules: `src/trace_vr/seeds.py`."
             % (t["split"], t["root_graphs"], t["sample_set"], t["n_boot"]), "",
             "| Arm | Seeds | Macro per seed | Pooled macro | Pooled - %s | Seed-matched diffs | Reading |" % t["reference"],
             "|---|---|---|---|---|---|---|"]
    for a in t["arms"]:
        per = ", ".join("%s: %.3f" % (s, v[MACRO]) for s, v in a["per_seed"].items())
        p = a["pooled"][MACRO]
        d = (a["vs_ref"] or {}).get(MACRO)
        ds = "ref" if d is None else "%+.3f [%+.3f, %+.3f]" % (d["point"], d["lo"], d["hi"])
        m = ", ".join("%s: %+.3f" % kv for kv in a.get("seed_matched_macro_diff", {}).items()) or "-"
        lines.append("| %s | %d | %s | %.3f [%.3f, %.3f] | %s | %s | %s |" % (
            a["label"], len(a["seeds"]), per, p["point"], p["lo"], p["hi"], ds, m, a.get("reading", "-")))
    return "\n".join(lines) + "\n"


def latex(t):
    """Booktabs tabular for the paper (\\input into a table float). Pooled accuracy per task, pooled macro interval,
    and the pooled macro difference to the reference with its interval."""
    ref = t["reference"].replace("_", "\\_")
    out = ["% Generated by scripts/seed_table.py; do not edit by hand.",
           "\\begin{tabular}{lcccccc}", "\\toprule",
           "Arm & Seeds & Repair & Reach. & Crit.\\ edge & Non-edit macro & $\\Delta$ macro vs %s \\\\" % ref,
           "\\midrule"]
    for a in t["arms"]:
        p = a["pooled"]
        cells = ["%.3f" % p[k]["point"] for k in ("minimal_graph_repair", "reachability", "critical_edge")]
        cells.append("%.3f {\\scriptsize[%.3f, %.3f]}" % (p[MACRO]["point"], p[MACRO]["lo"], p[MACRO]["hi"]))
        d = (a["vs_ref"] or {}).get(MACRO)
        cells.append("ref" if d is None else "$%+.3f$ {\\scriptsize[$%+.3f$, $%+.3f$]}" % (d["point"], d["lo"], d["hi"]))
        out.append("%s & %d & %s \\\\" % (a["label"].replace("_", "\\_"), len(a["seeds"]), " & ".join(cells)))
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out) + "\n"


def main(argv):
    manifest, entries, opts = parse(argv)
    t = build(manifest, entries, opts["ref"], int(opts["boot"]))
    md = markdown(t)
    for key, text in (("out-json", json.dumps(t, indent=1) + "\n"), ("out-md", md), ("out-tex", latex(t))):
        if opts[key]:
            Path(opts[key]).parent.mkdir(parents=True, exist_ok=True)
            Path(opts[key]).write_text(text)
    print(md, end="")


if __name__ == "__main__":
    main(sys.argv[1:])
