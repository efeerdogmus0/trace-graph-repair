"""Pre-release audit of the tracked files (read-only; publishes nothing).

Checks every file `git ls-files` lists:
  * secrets: token-shaped strings (Kaggle KGAT_, Hugging Face hf_, GitHub ghp_/github_pat_,
    OpenAI/Anthropic sk-, AWS AKIA, private-key blocks) -> any hit fails the audit;
  * local paths: absolute home-directory paths (/Users/<name>, /home/<name>) -> fail;
  * review items: account handles and private links that are not secret but should be
    replaced or confirmed by the owner before a public upload (Kaggle account slug,
    Colab Drive notebook links, e-mail addresses);
  * internal files: project-management notes that a public code release would normally
    leave out (runbook, state, decision log, original brief, prior-chat notes);
  * size: files over --max-mb.

Exit code 1 if a secret or local path is found, else 0. Review items never fail the audit:
they are decisions for the owner, listed with file and line.

    python scripts/release_audit.py --out-md reports/release_audit.md
"""
import argparse, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SECRET_PATTERNS = {
    "kaggle_token": r"KGAT_[A-Za-z0-9]{16,}",
    "hf_token": r"\bhf_[A-Za-z0-9]{30,}",
    "github_token": r"\b(?:ghp|gho|ghs|ghu)_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{40,}",
    "api_key_sk": r"\bsk-(?:ant-)?[A-Za-z0-9_-]{20,}",
    "aws_key": r"\bAKIA[0-9A-Z]{16}\b",
    "private_key": r"-----BEGIN [A-Z ]*PRIVATE KEY-----",
}
LOCAL_PATH_PATTERNS = {
    "home_path": r"(?<![\w.])/(?:Users|home)/(?!runner\b)[A-Za-z0-9._-]+/",
}
REVIEW_PATTERNS = {
    "kaggle_account": r"yiitefeerdomu|efeerdogmus1",  # main and shared Kaggle accounts
    "colab_drive_link": r"colab\.research\.google\.com/drive/[A-Za-z0-9_-]+",
    "email": r"\b[A-Za-z0-9._%+-]+@(?!example\.)[A-Za-z0-9.-]+\.[a-z]{2,}\b",
}
# Notes for running the project, not part of a code/benchmark release.
INTERNAL_FILES = ("RUNBOOK.md", "PROJECT_STATE.md", "DECISIONS.md", "PLAN.md", "BLOCKERS.md",
                  "TRACE_ASTRA_MASTER_PROMPT.md", "docs/prior_gpt_work.md")
# This file and its test name the patterns on purpose.
SELF = ("scripts/release_audit.py", "tests/test_release_audit.py")


def tracked_files(root=ROOT):
    out = subprocess.run(["git", "ls-files", "-z"], cwd=root, capture_output=True, check=True).stdout
    return [p for p in out.decode().split("\0") if p]


def scan_text(text, patterns):
    hits = []
    for name, pat in patterns.items():
        rx = re.compile(pat)
        for i, line in enumerate(text.splitlines(), 1):
            if rx.search(line):
                hits.append((name, i))
    return hits


def audit(files, read, size, max_mb=5.0):
    """files: relative paths; read(path) -> str or None (binary); size(path) -> bytes."""
    res = {"secrets": [], "local_paths": [], "review": [], "internal": [], "large": [], "binary": 0}
    for f in files:
        if size(f) > max_mb * 1e6:
            res["large"].append((f, size(f)))
        if f in INTERNAL_FILES:
            res["internal"].append(f)
        if f in SELF:
            continue
        text = read(f)
        if text is None:
            res["binary"] += 1
            continue
        res["secrets"] += [(f, n, i) for n, i in scan_text(text, SECRET_PATTERNS)]
        res["local_paths"] += [(f, n, i) for n, i in scan_text(text, LOCAL_PATH_PATTERNS)]
        res["review"] += [(f, n, i) for n, i in scan_text(text, REVIEW_PATTERNS)]
    res["ok"] = not res["secrets"] and not res["local_paths"]
    return res


def render_md(res, n_files):
    L = ["# Release audit", "",
         "Generated by `scripts/release_audit.py` over `git ls-files` (%d files). Nothing is published." % n_files,
         "", "Verdict: **%s** (secrets: %d, local paths: %d; review items never fail)." %
         ("pass" if res["ok"] else "FAIL", len(res["secrets"]), len(res["local_paths"])), ""]
    for key, title in (("secrets", "Secrets"), ("local_paths", "Local paths")):
        L += ["## %s" % title, ""]
        L += ["- `%s:%d` (%s)" % (f, i, n) for f, n, i in res[key]] or ["None."]
        L.append("")
    L += ["## Review before a public upload (owner decision)", ""]
    by = {}
    for f, n, i in res["review"]:
        by.setdefault(n, {}).setdefault(f, []).append(i)
    if not by:
        L.append("None.")
    for n in sorted(by):
        L.append("- **%s**: %d file(s)" % (n, len(by[n])))
        for f in sorted(by[n]):
            L.append("  - `%s` lines %s" % (f, ", ".join(map(str, by[n][f]))))
    L += ["", "## Internal project notes (leave out of a code release, or keep deliberately)", ""]
    L += ["- `%s`" % f for f in res["internal"]] or ["None."]
    L += ["", "## Files over the size limit", ""]
    L += ["- `%s` (%.1f MB)" % (f, s / 1e6) for f, s in res["large"]] or ["None."]
    L += ["", "Binary files skipped by the text scan: %d." % res["binary"], ""]
    return "\n".join(L)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-md")
    ap.add_argument("--max-mb", type=float, default=5.0)
    a = ap.parse_args(argv)
    files = tracked_files()

    def read(f):
        b = (ROOT / f).read_bytes()
        if b"\0" in b[:8192]:
            return None
        return b.decode("utf-8", errors="replace")

    res = audit(files, read, lambda f: (ROOT / f).stat().st_size, a.max_mb)
    md = render_md(res, len(files))
    if a.out_md:
        Path(a.out_md).write_text(md)
    print("RELEASE-AUDIT files=%d secrets=%d local_paths=%d review=%d internal=%d large=%d -> %s" % (
        len(files), len(res["secrets"]), len(res["local_paths"]), len(res["review"]),
        len(res["internal"]), len(res["large"]), "pass" if res["ok"] else "FAIL"))
    return 0 if res["ok"] else 1


if __name__ == "__main__":
    sys.exit(main())
