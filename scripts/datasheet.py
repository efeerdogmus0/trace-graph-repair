"""Generate the statistics part of a dataset datasheet from a manifest and its validation report.

Usage: python scripts/datasheet.py <manifest.json> <validation.json> [out.md]

Every number in the output is read from the two files; nothing is typed by hand. The prose
part of the datasheet (motivation, intended use, limits) lives in docs/datasheet.md and links
to the generated file.
"""
import json
import sys
from pathlib import Path

ORDERED_KEYS = [
    ("root_family", "Root graphs by family"),
    ("root_node_count", "Root graphs by node count"),
    ("root_edge_count", "Root graphs by edge count"),
    ("root_layout", "Root graphs by layout"),
    ("root_style", "Root graphs by drawing style"),
    ("root_crossings", "Root graphs by edge crossings"),
    ("images_by_variant", "Images by variant"),
    ("samples_by_task", "Samples by task"),
    ("pairs_by_kind", "Pairs by kind"),
    ("repair_category", "Repair answers (all repair samples)"),
    ("repair_category_on_root_images", "Repair answers on root images"),
    ("repair_direct_share_on_root_images", "Repair goal names an addable edge (root images)"),
    ("shortest_path_answers", "Shortest-path answers"),
]


def _sortkey(k):
    try:
        return (0, float(k), "")
    except ValueError:
        return (1, 0.0, k)


def _table(title, splits, per_split):
    keys = sorted({k for s in splits for k in per_split.get(s, {})}, key=_sortkey)
    lines = ["### %s" % title, "", "| value | " + " | ".join(splits) + " |",
             "|---|" + "---:|" * len(splits)]
    for k in keys:
        lines.append("| %s | " % k + " | ".join(str(per_split.get(s, {}).get(k, 0)) for s in splits) + " |")
    lines.append("| **total** | " + " | ".join(str(sum(per_split.get(s, {}).values())) for s in splits) + " |")
    return lines + [""]


def render(manifest, validation):
    splits = list(manifest.get("split_order") or manifest["splits"].keys())
    st = manifest["stats"]
    out = [
        "# Datasheet statistics: `%s`" % manifest["name"],
        "",
        "Generated by `scripts/datasheet.py` from the manifest and validation report; do not edit by hand.",
        "",
        "| field | value |", "|---|---|",
        "| generator version | `%s` |" % manifest["generator_version"],
        "| content digest (labels, graphs, instructions) | `%s` |" % manifest["content_digest"],
        "| images digest (machine-specific PNG bytes) | `%s` |" % manifest["images_digest"],
        "| config sha256 | `%s` |" % manifest["config_sha256"],
        "| build environment | %s |" % ", ".join("%s %s" % kv for kv in sorted(manifest["build_environment"].items())),
        "| validator | ok=%s, %d checks, %d errors, %d warnings |" % (
            validation["ok"], validation["total_checks"], validation["error_count"], len(validation["warnings"])),
        "",
        "## Size per split", "",
        "| split | root graphs | images | samples |", "|---|---:|---:|---:|",
    ]
    for s in splits:
        sp = manifest["splits"][s]
        out.append("| %s | %d | %d | %d |" % (s, sp["roots"], sp["images"], sp["samples"]))
    out += ["", "## Distributions", ""]
    for key, title in ORDERED_KEYS:
        out += _table(title, splits, {s: st[s].get(key, {}) for s in splits})
    out += ["## Answer balance (yes/no tasks)", "",
            "| task | split | all samples: true / false | root images only: true / false |", "|---|---|---|---|"]
    for task in sorted({k.split(":", 1)[1] for s in splits for k in st[s] if k.startswith("answer_balance:")}):
        for s in splits:
            a = st[s].get("answer_balance:" + task, {})
            r = st[s].get("answer_on_root_images:" + task, {})
            out.append("| %s | %s | %d / %d | %d / %d |" % (task, s, a.get("True", 0), a.get("False", 0),
                                                           r.get("True", 0), r.get("False", 0)))
    out += ["", "## Model-free baselines (validator, real scorer)", "",
            "A text-only ceiling of 0.50 means every instruction has an answer-flipping twin image.", "",
            "| split | task | samples | probe | accuracy |", "|---|---|---:|---|---:|"]
    for s in splits:
        for task, probes in sorted(validation["text_only_shortcuts"].get(s, {}).items()):
            for probe, val in sorted(probes.items()):
                if probe != "samples":
                    out.append("| %s | %s | %d | %s | %.4f |" % (s, task, probes["samples"], probe, val))
    out += ["", "## Generation rejections", "", "| split | reason | count |", "|---|---|---:|"]
    for s in splits:
        for reason, n in sorted(manifest.get("rejections", {}).get(s, {}).items()):
            out.append("| %s | %s | %d |" % (s, reason, n))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    man = json.loads(Path(sys.argv[1]).read_text())
    val = json.loads(Path(sys.argv[2]).read_text())
    text = render(man, val)
    if len(sys.argv) > 3:
        Path(sys.argv[3]).write_text(text)
        print("wrote", sys.argv[3])
    else:
        sys.stdout.write(text)
