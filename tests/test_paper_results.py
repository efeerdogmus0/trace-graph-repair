"""paper/sections/results.tex states only numbers from results_dev.json and go_no_go_rev1.json."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEX = " ".join((ROOT / "paper/sections/results.tex").read_text().split())
MAIN = (ROOT / "paper/main.tex").read_text()
T = json.loads((ROOT / "reports/pilot/results_dev.json").read_text())
G = json.loads((ROOT / "runs/go_no_go_rev1.json").read_text())
ARMS = {a["label"]: a for a in T["arms"]}
M = "non_edit_macro_accuracy"


def f(x):
    return "%.3f" % x


def interval(e):
    return "$%s$ ($%s$ to $%s$)" % (("%+.3f" % e["point"]).replace("+", "") if e["point"] < 0 else "+" + f(e["point"]),
                                   ("%+.3f" % e["lo"]).replace("+", "") if e["lo"] < 0 else "+" + f(e["lo"]),
                                   ("%+.3f" % e["hi"]).replace("+", "") if e["hi"] < 0 else "+" + f(e["hi"]))


def test_wired_and_table_generated():
    assert "\\input{sections/results}" in MAIN and "\\section{Results}" not in MAIN
    assert "\\input{tables/results_dev}" in TEX
    tab = (ROOT / "paper/tables/results_dev.tex").read_text()
    assert tab.startswith("% Generated by scripts/results_table.py")
    for line in tab.splitlines()[1:]:  # no bare underscore outside math: would not compile
        assert "_" not in line.replace("\\_", ""), line


def test_setup_numbers():
    assert T["split"] == "dev" and T["root_graphs"] == 200 and T["n_boot"] == 2000
    assert T["reference"] == "B_kaggle"
    assert "200 development root graphs" in TEX and "2000 replicates" in TEX


def test_go_no_go_paragraph():
    e = G["entries"]
    assert G["decision"] == "close_H1_not_supported"
    for k in ("d_vs_b", "d2_vs_b"):
        assert interval(e[k]) in TEX and e[k]["share_above_zero"] == 0.0
    assert interval(e["machine"]) in TEX
    assert "no bootstrap replicate of either difference was above zero" in TEX


def test_table_numbers():
    c = ARMS["C_kaggle"]
    assert "macro of $%s$, %s below B" % (f(c["acc"][M]["point"]), interval(c["vs_ref"][M])) in TEX
    assert "accuracy ($%s$)" % f(c["acc"]["critical_edge"]["point"]) in TEX
    assert c["acc"]["critical_edge"]["point"] < 0.5
    rep = {k: f(ARMS[k]["acc"]["minimal_graph_repair"]["point"]) for k in ("D_colab", "D2_kaggle", "B_kaggle", "C_kaggle")}
    assert "D ($%s$) and D2 ($%s$) are well above B ($%s$) and C ($%s$)" % (
        rep["D_colab"], rep["D2_kaggle"], rep["B_kaggle"], rep["C_kaggle"]) in TEX


P = json.loads((ROOT / "reports/pilot/perception_split_dev.json").read_text())


def test_e_paragraph():
    e = ARMS["E_kaggle"]
    assert "non-edit macro of $%s$, %s above B" % (f(e["acc"][M]["point"]), interval(e["vs_ref"][M])) in TEX
    assert e["vs_ref"][M]["lo"] > 0
    assert "$%s$ on repair" % f(e["acc"]["minimal_graph_repair"]["point"]) in TEX
    assert "exact for only $%d$ of $%d$ development images" % (P["readable_images"], P["images"]) in TEX
    assert P["reference"] == "B_kaggle" and P["split"] == "dev"
    d = P["arms"]["D_colab"]
    assert d["reading"] == "reasoning_gap"
    assert "D is still %s below B" % interval(d["readable"]["vs_ref"]) in TEX
