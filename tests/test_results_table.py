"""results_table.py reproduces the committed go/no-go numbers and refuses mismatched flag files."""
import json, subprocess, sys
from pathlib import Path
import pytest

ROOT = Path(__file__).resolve().parents[1]
MAN = ROOT / "manifests/pilot.json"
pytestmark = pytest.mark.skipif(not (ROOT / "data/pilot/dev.samples.jsonl").exists(), reason="pilot data not built")
ARMS = ["B_kaggle=runs/pilot3_B_kaggle/flags_dev.json", "B_colab=runs/pilot3_B/flags_dev.json",
        "D2_kaggle=runs/pilot3_D2/flags_dev.json"]


def _run(*args):
    return subprocess.run([sys.executable, "scripts/results_table.py", str(MAN), *args], cwd=ROOT,
                          capture_output=True, text=True, env={"PYTHONPATH": str(ROOT / "src"), "PATH": "/usr/bin:/bin"})


def test_matches_go_no_go_record(tmp_path):
    out = tmp_path / "t.json"; tex = tmp_path / "t.tex"
    res = _run("--ref", "B_kaggle", *ARMS, "--out-json", str(out), "--out-tex", str(tex), "--boot", "2000")
    assert res.returncode == 0, res.stderr
    t = json.loads(out.read_text())
    rec = json.loads((ROOT / "runs/go_no_go_rev1.json").read_text())["entries"]
    by = {a["label"]: a for a in t["arms"]}
    assert by["B_kaggle"]["vs_ref"] is None
    for label, key, sign in (("D2_kaggle", "d2_vs_b", 1), ("B_colab", "machine", -1)):
        d = by[label]["vs_ref"]["non_edit_macro_accuracy"]
        assert d["point"] * sign == pytest.approx(rec[key]["point"], abs=1e-9)
    d = by["D2_kaggle"]["vs_ref"]["non_edit_macro_accuracy"]
    assert (d["lo"], d["hi"]) == pytest.approx((rec["d2_vs_b"]["lo"], rec["d2_vs_b"]["hi"]), abs=1e-9)
    assert "Generated by scripts/results_table.py" in tex.read_text()


def test_refuses_different_root_counts(tmp_path):
    res = _run("--ref", "B", "B=runs/pilot3_B/flags_dev.json", "E=runs/pilot3_B_kaggle_edges/flags_dev_edges.json")
    assert res.returncode != 0 and "different samples" in res.stderr


def test_refuses_unknown_reference():
    res = _run("--ref", "X", "B=runs/pilot3_B/flags_dev.json")
    assert res.returncode != 0
