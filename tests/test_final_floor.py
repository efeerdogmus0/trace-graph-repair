"""final_floor.py: the frozen-base floor on the locked test is all-or-nothing (the base run and the twelve queue entries),
checks the dev-chosen prompt and the flags file, and reports one run with root-graph intervals. Metrics and flags come
from constant answers scored against the labels, so no model output on the locked test is involved."""
import importlib.util, json
from pathlib import Path
import pytest
from trace_vr import arms, bootstrap, dataset, metrics, tasks

ROOT = Path(__file__).resolve().parents[1]
SMALL = [("pilot_test", "test_id", 40), ("pilot_diag", "test_size_ood", 30)]
needs_data = pytest.mark.skipif(not (ROOT / "data/pilot_test/test_id.samples.jsonl").exists()
                                or not (ROOT / "data/pilot_diag/test_size_ood.samples.jsonl").exists(),
                                reason="locked test data not built")
BASE = {"job": "jobF13", "arm": "A", "run": "base_prompt_system", "dev_dir": "runs/base_prompt_system", "variant": "system",
        "limit": 96, "expect": {"adapter": "none", "prompt_variant": "system", "max_new_tokens": 96}}


def load():
    spec = importlib.util.spec_from_file_location("final_floor", ROOT / "scripts/final_floor.py")
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def _jobs():
    return [{"job": "jobF%s%d" % (a, s), "arm": a, "seed": s, "dev_dir": "runs/%s_%d" % (a, s)}
            for s in (3407, 2027, 9173) for a in ("B", "C", "D", "E")]


def _write(tmp_path, entries, answer='{"answer": true}', expect=BASE["expect"], skip=None):
    for e in entries:
        d = tmp_path / e["dev_dir"]; d.mkdir(parents=True)
        summary = {"metrics": {}}
        for manifest, split, roots in SMALL:
            man, _, by_split, _ = dataset.load_dataset(ROOT / "manifests" / (manifest + ".json"))
            rows = arms.select_samples(by_split[split], roots, "main")
            resp = {s["sample_id"]: answer for s in rows}
            head = {"split": split, "sample_set": "main", "eval_root_graphs": roots, "content_digest": man["content_digest"]}
            summary["metrics"][split] = dict(head, truncated_at_limit=0, metrics=metrics.evaluate(rows, resp, lenient=True), **expect)
            if skip == (e["job"], split):
                continue
            out = bootstrap.score_flags(rows, resp)
            out.update(head)
            (d / ("flags_%s.json" % split)).write_text(json.dumps(out))
        (d / "final_summary.json").write_text(json.dumps(summary))


@needs_data
def test_floor_reports_one_run_with_intervals(tmp_path):
    m = load()
    _write(tmp_path, _jobs() + [BASE])
    t = m.build(BASE, _jobs(), SMALL, n_boot=200, root=tmp_path)
    assert t["splits"] == ["test_id", "test_size_ood"] and t["job"] == "jobF13" and t["variant"] == "system"
    for manifest, split, roots in SMALL:
        man, _, by_split, _ = dataset.load_dataset(ROOT / "manifests" / (manifest + ".json"))
        rows = arms.select_samples(by_split[split], roots, "main")
        truth = metrics.evaluate(rows, {s["sample_id"]: '{"answer": true}' for s in rows}, lenient=True)
        x = t["tables"][split]
        assert x["root_graphs"] == roots
        for task, cell in truth["per_task"].items():
            assert x["per_task"][task]["accuracy"] == pytest.approx(cell["accuracy"])
            assert x["interval"][task]["point"] == pytest.approx(cell["accuracy"])
            assert x["interval"][task]["lo"] <= x["interval"][task]["point"] <= x["interval"][task]["hi"]
        non_edit = [truth["per_task"][k]["accuracy"] for k in truth["per_task"] if k != tasks.REPAIR]
        assert x["interval"][m.MACRO]["point"] == pytest.approx(sum(non_edit) / len(non_edit))
    md = m.markdown(t)
    assert "reported floor, not a compared arm" in md and "| test_id | 40 | " in md and " - " not in md.split("\n")[0][:5]
    tex = m.latex(t).splitlines()
    assert tex[0].startswith("% Generated by scripts/final_floor.py") and tex[-1] == "\\end{tabular}"
    assert len([l for l in tex if l.startswith("test\\_")]) == 2


@needs_data
def test_refuses_while_a_compared_run_is_missing(tmp_path):
    m = load()
    _write(tmp_path, _jobs() + [BASE], skip=("jobFE9173", "test_size_ood"))
    with pytest.raises(SystemExit, match="jobFE9173"):
        m.build(BASE, _jobs(), SMALL, n_boot=50, root=tmp_path)


@needs_data
def test_refuses_while_the_base_run_is_missing(tmp_path):
    m = load()
    _write(tmp_path, _jobs())
    with pytest.raises(SystemExit, match="jobF13"):
        m.build(BASE, _jobs(), SMALL, n_boot=50, root=tmp_path)


@needs_data
def test_refuses_a_prompt_other_than_the_dev_choice(tmp_path):
    m = load()
    _write(tmp_path, _jobs())
    _write(tmp_path, [BASE], expect={"adapter": "none", "prompt_variant": "common", "max_new_tokens": 768})
    with pytest.raises(SystemExit, match="dev choice"):
        m.build(BASE, _jobs(), SMALL, n_boot=50, root=tmp_path)


@needs_data
def test_refuses_metrics_that_disagree_with_flags(tmp_path):
    m = load()
    _write(tmp_path, _jobs() + [BASE])
    p = tmp_path / BASE["dev_dir"] / "final_summary.json"
    s = json.loads(p.read_text())
    s["metrics"]["test_id"]["metrics"]["per_task"][tasks.REACHABILITY]["accuracy"] += 0.01
    p.write_text(json.dumps(s))
    with pytest.raises(SystemExit, match="reachability accuracy in the metrics file differs"):
        m.build(BASE, _jobs(), SMALL, n_boot=50, root=tmp_path)


def test_real_queue_is_refused_and_prints_nothing(capsys):
    q = json.loads((ROOT / "scripts/kaggle/final_queue.json").read_text())
    if all((ROOT / "runs/kaggle" / j["job"]).exists() for j in q["jobs"] + [q["base"]]):
        pytest.skip("all final runs and the frozen base collected")
    if (ROOT / "reports/final/final_primary.json").exists():   # public release: reports tracked, raw runs not shipped
        pytest.skip("locked test already read; its reports are tracked")
    m = load()
    with pytest.raises(SystemExit, match="not collected"):
        m.main([])
    assert capsys.readouterr().out == ""
